#!/usr/bin/env python3
"""Import source TM31/TM51 definitions without renumbering target/save items."""
import argparse
import base64
import hashlib
import json
import re

import build_pokemon_learnsets as learnsets
from build_new_bark import source_files
from build_tm70 import sources
from polished_route30 import palette

ROOT, PIN = learnsets.ROOT, learnsets.PIN


def build():
    raw = sources()
    folder = ROOT / 'tools/polished_port/fixtures/source_tms'
    fixture = json.loads((folder / 'sources.json').read_text())
    assert fixture['commit'] == PIN
    for entry in fixture['files']:
        data = base64.b64decode((folder / entry['fixture']).read_bytes())
        assert hashlib.sha1(b'blob ' + str(len(data)).encode() + b'\0' + data).hexdigest() == entry['git_blob_sha1']
        raw[entry['path']] = data
    source = learnsets.sources()
    moves = {row[0]: row for row in ([v.strip() for v in line[5:].split(',')]
             for line in learnsets.default_lines(source['data/moves/moves.asm']) if line.startswith('move '))}
    tms = re.findall(r'^\s*add_tm (\w+)', raw['constants/tmhm_constants.asm'].decode(), re.M)
    assert tms[30] == 'ROCK_SMASH' and tms[50] == 'ROOST'
    identities = {r['source_constant']: r for r in learnsets.move_identities(source)[1:]}
    types = re.findall(r'^\s*const (\w+)', raw['constants/type_constants.asm'].decode().split('; categories')[0], re.M)
    colors = [tuple(map(int, c)) for c in re.findall(r'RGB\s+(\d+),\s*(\d+),\s*(\d+)', raw['gfx/items/tm_hm_types.pal'].decode())]
    assert len(colors) == 2 * len(types)
    descriptions = '\n'.join(learnsets.default_lines(raw['data/moves/descriptions.asm'].decode()))
    # The source's stale event label says TM31; the actual instruction awards
    # TM_ROOST (machine number 51). Never derive identity from the flag's name.
    gym = source_files()['maps/VioletGym.asm'].decode()
    assert 'verbosegivetmhm TM_ROOST\n\tsetevent EVENT_GOT_TM31_ROOST' in gym
    result, records = {}, []
    for number, label, target_id in ((31, 'RockSmash', 612), (51, 'Roost', 632)):
        identity = identities[tms[number - 1]]
        move = identity['source_move']
        assert move == {31: 'BRICK_BREAK', 51: 'ROOST'}[number]
        row = moves[move]
        move_type, pp = row[3], int(row[5])
        shades = colors[types.index(move_type)*2:types.index(move_type)*2+2]
        description = '\\n'.join(re.findall(r'(?:text|next) "(.*)"', descriptions.split(label+'Description:', 1)[1].split('done', 1)[0]))
        assert description
        result[ROOT/f'graphics/items/icon_palettes/polished_tm_{move_type.lower()}.pal'] = palette(shades)
        result[ROOT/f'src/data/polished_tm{number}_item.h'] = f'''/* Generated by build_source_tms.py from Polished Crystal {PIN}. */
    [ITEM_TM_{move}] =
    {{
        .name = ITEM_NAME("TM{number}"),
        .price = 0, // Source machine ownership is nontradable and reusable.
        .description = COMPOUND_STRING("{description}"),
        .importance = TRUE,
        .pocket = POCKET_TM_HM,
        .type = ITEM_USE_PARTY_MENU,
        .fieldUseFunc = ItemUseOutOfBattle_TMHM,
        .iconPic = gItemIcon_PolishedTM,
        .iconPalette = gItemIconPalette_PolishedTM{move_type.title()},
    }},
'''.encode()
        records.append(dict(number=number, source_constant=tms[number-1], source_move=move,
            target_item='ITEM_TM_'+move, target_id=target_id, target_move=identity['target_move'],
            source_type=move_type, source_rgb555=shades, source_dimensions=[24,24],
            source_pp=pp, description=description))
    report = dict(source_commit=PIN, source_variant='default (FAITHFUL undefined)', machines=records,
        rules=['Original shared machine icon; source Fighting and Flying palettes selected by source move type.',
               'Existing target/save IDs, machine indices and numbers retained; no inventory migration.',
               'Reusable, nontradable bag items adapt source machine ownership bits.',
               'Source compatibility, lesson friendship and actual Bag PP flow are shared with TM70.',
               'Falkner already awards TM51 once; its existing item ID now receives the source definition.'],
        gaps=['Other source TM/HM/tutor identities and source ownership-bit inventory remain incomplete.',
              'Native Bag, party, learning text, sound and animation remain presentation gaps.',
              'TM31 acquisition beyond the imported campaign remains unported; fixture ownership is not campaign acquisition.',
              'Move battle effects and other move data remain separately audited; this suite covers item identity and teaching.'])
    result[ROOT/'tools/polished_port/manifests/source_tms.json'] = (json.dumps(report, indent=2)+'\n').encode()
    return result


if __name__ == '__main__':
    p=argparse.ArgumentParser(description=__doc__); p.add_argument('--check',action='store_true'); a=p.parse_args()
    for path, data in build().items():
        if a.check:
            assert path.exists() and path.read_bytes()==data, f'Regenerate {path}'
        else:
            path.parent.mkdir(parents=True,exist_ok=True); path.write_bytes(data)
    print('PASS: source TM31 Brick Break and TM51 Roost identities, descriptions, type palettes and PP')
