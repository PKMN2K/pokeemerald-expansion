#!/usr/bin/env python3
"""Stage an Emerald-shaped Johto test-map package outside live registration.

Outputs may be reviewed or imported manually after remaining blockers are
resolved. This command never writes data/maps, data/layouts or map_groups.json.
"""
import argparse
import hashlib
import json
import re
import struct
from pathlib import Path
from prepare_johto_layout_registration import prepare, ROOT, ID, NAME
from export_johto_tileset_bundle import export as export_tileset
from export_johto_test_metatile_bindings import export as export_bindings
from export_johto_obstacle_collision_review import export as export_obstacles
from audit_johto_obstacle_foreground_priority import inspect as inspect_obstacle_priority
from export_johto_sprite_occlusion_probes import export as export_sprite_probes
from audit_johto_full_layer_attribute_coverage import audit as audit_all_layers
from export_johto_wall_mapgrid_rules import export as export_wall_rules
from export_johto_water_ledge_field_probes import export as export_water_ledge_probes
from export_johto_surf_shoreline_probes import export as export_surf_shoreline
from export_johto_extended_behavior_review import export as export_extended_behaviors
from export_johto_source_wall_permissions import export as export_wall_permissions
from export_johto_headbutt_field_probes import export as export_headbutt

MAP_ID = "MAP_POLISHED_JOHTO_WALKABILITY_TEST"
MAP_NAME = "PolishedJohto_WalkabilityTest"
# Use real repo constants for a deliberately silent, otherwise neutral test map.
# These values are NOT a Johto music/region-map integration decision.
HEADER_CONSTANTS = {
    "music": ("MUS_DUMMY", "include/constants/songs.h"),
    "region": ("REGION_JOHTO", "include/constants/regions.h"),
    "weather": ("WEATHER_NONE", "include/constants/weather.h"),
    "map_type": ("MAP_TYPE_ROUTE", "include/constants/map_types.h"),
    "battle_scene": ("MAP_BATTLE_SCENE_NORMAL", "include/constants/map_types.h"),
}
# The renderer/region map does not yet have Johto geography. MAPSEC_NONE is
# generated by the existing constants template and deliberately has no Hoenn
# coordinates. This placeholder is never counted as Johto region-map support.
MISSING_HEADER_FIELDS = ("region_map_section",)
REGION_MAP_PLACEHOLDER = "MAPSEC_NONE"

def verify_region_map_placeholder():
    data = json.loads((ROOT / "src/data/region_map/region_map_sections.json").read_text(
        encoding="utf-8"
    ))
    entries = data["map_sections"]
    ids = [row["id"] for row in entries]
    assert len(ids) == len(set(ids))
    assert REGION_MAP_PLACEHOLDER not in ids
    template = (ROOT / "src/data/region_map/region_map_sections.constants.json.txt").read_text(
        encoding="utf-8"
    )
    assert re.search(r"(?m)^\s*MAPSEC_NONE,\s*$", template)
    assert not any(id.startswith("MAPSEC_JOHTO_") for id in ids)
    return {"section": REGION_MAP_PLACEHOLDER,
            "source_entries": len(ids),
            "native_johto_map_section_registered": False,
            "actual_johto_placement_verified": False}

def verify_header_constants():
    for field, (name, path) in HEADER_CONSTANTS.items():
        body = (ROOT / path).read_text(encoding="utf-8")
        pattern = (r"(?m)^\s*#define\s+" if field == "music" else r"(?m)^\s*")
        pattern += re.escape(name)
        pattern += (r"\s+\d+\b" if field == "music" else r"(?:\s*,|\s*=)")
        assert re.search(pattern, body), f"missing source-backed constant {name} in {path}"
    return {field: name for field, (name, _) in HEADER_CONSTANTS.items()}


def stage(output):
    output = output.resolve()
    repo = ROOT.resolve()
    if output == repo or repo in output.parents:
        raise ValueError("Offline map package output must be outside repository")
    reports = output / "reviews"
    report = prepare(reports)
    layouts = json.loads((ROOT / "data/layouts/layouts.json").read_text(encoding="utf-8"))["layouts"]
    reference_layout = next(x for x in layouts if x["id"] == "LAYOUT_ROUTE101")
    proposed_layout = report["layout_proposal"]
    assert set(proposed_layout) == set(reference_layout), "Not a native Emerald layout record"
    assert proposed_layout["layout_version"] == "emerald"
    assert proposed_layout["id"] == ID and proposed_layout["name"] == NAME
    assert not any(x["id"] == ID or x["name"] == NAME for x in layouts)

    groups = json.loads((ROOT / "data/maps/map_groups.json").read_text(encoding="utf-8"))
    assert not any(MAP_NAME in values for values in groups.values() if isinstance(values, list))
    reference_map = json.loads((ROOT / "data/maps/Route101/map.json").read_text(encoding="utf-8"))
    constants = verify_header_constants()
    region_placeholder = verify_region_map_placeholder()
    header = {
        "id": MAP_ID, "name": MAP_NAME, "layout": ID,
        "music": constants["music"], "region": constants["region"],
        "region_map_section": region_placeholder["section"],
        "requires_flash": False, "weather": constants["weather"],
        "map_type": constants["map_type"],
        "allow_cycling": False, "allow_escaping": False,
        "allow_running": True, "show_map_name": False,
        "battle_scene": constants["battle_scene"], "connections": [], "object_events": [],
        "warp_events": [], "coord_events": [], "bg_events": [],
    }
    assert set(header) == set(reference_map), "Map-header draft does not match native schema"
    assert all(header[field] == REGION_MAP_PLACEHOLDER for field in MISSING_HEADER_FIELDS)
    assert all(header[field] == name for field, name in constants.items())
    assert all(value is not None for value in header.values())
    assert not region_placeholder["native_johto_map_section_registered"]
    assert not any(header[k] for k in (
        "connections", "object_events", "warp_events", "coord_events", "bg_events"
    ))

    root = output / "OFFLINE_ONLY" / "data" / "layouts" / MAP_NAME
    root.mkdir(parents=True, exist_ok=True)
    map_raw = (reports / "johto_basic_walkability_layout.bin").read_bytes()
    border_raw = (reports / "johto_basic_border_candidate.bin").read_bytes()
    assert len(map_raw) == 8 * 8 * 2 and len(border_raw) == 2 * 2 * 2
    assert struct.unpack("<64H", map_raw) == tuple(
        cell["packed_cell"] for cell in json.loads(
            (reports / "johto_basic_walkability_layout.json").read_text()
        )["cells"]
    )
    assert struct.unpack("<4H", border_raw) == tuple(
        json.loads((reports / "johto_basic_border_candidate.json").read_text())["packed_cells"]
    )
    (root / "map.bin").write_bytes(map_raw)
    (root / "border.bin").write_bytes(border_raw)
    # Development teleport position only; NOT a warp, event, or ROM entry point.
    cells = json.loads((reports / "johto_basic_walkability_layout.json").read_text())["cells"]
    spawn = cells[1 + 1 * 8]
    assert (spawn["x"], spawn["y"]) == (1, 1)
    assert spawn["source_symbol"] == "FLOOR" and spawn["candidate_attribute_word"] == 0
    assert (spawn["packed_cell"] >> 12) == 3
    spawn_plan = {"map_id": MAP_ID, "x": 1, "y": 1, "elevation": 3,
                  "source_metatile_id": spawn["metatile_id"],
                  "proposed_debug_teleport_only": True,
                  "warp_or_map_group_registered": False,
                  "in_emulator_verified": False}
    (output / "OFFLINE_ONLY" / "debug_spawn.review.json").write_text(
        json.dumps(spawn_plan, indent=2) + "\n", encoding="utf-8"
    )

    # Pinned real-source graphics and palettes are kept as another offline folder.
    assets = output / "OFFLINE_ONLY" / "johto_source_tileset"
    export_tileset(assets)
    bindings = export_bindings(
        output / "OFFLINE_ONLY" / "attribute_bindings",
        map_raw, border_raw,
        (assets / "johto_primary_metatiles.bin").read_bytes(),
        (assets / "johto_secondary_metatiles.bin").read_bytes(),
    )
    assert bindings["map_cells_checked"] == 64
    assert bindings["border_cells_checked"] == 4
    assert bindings["binding_count"] > 0
    assert not bindings["live_registration_allowed"]
    obstacle_review = export_obstacles(
        output / "OFFLINE_ONLY" / "obstacle_collision_review",
        map_raw,
        (assets / "johto_primary_metatiles.bin").read_bytes(),
        (assets / "johto_secondary_metatiles.bin").read_bytes(),
    )
    assert obstacle_review["changed_cells"] == 6
    assert not obstacle_review["safe_to_register"]
    assert not obstacle_review["emulator_collision_verified"]
    obstacle_review_dir = output / "OFFLINE_ONLY" / "obstacle_collision_review"
    layer_review = inspect_obstacle_priority(
        obstacle_review_dir,
        obstacle_review,
        (obstacle_review_dir / "johto_obstacle_collision.review.bin").read_bytes(),
        (assets / "johto_primary_metatiles.bin").read_bytes(),
        (assets / "johto_secondary_metatiles.bin").read_bytes(),
        (assets / "johto_primary.4bpp").read_bytes(),
    )
    assert layer_review["obstacle_metatiles_checked"] == 6
    assert not layer_review["sprite_elevation_parity_verified_in_emulator"]
    sprite_probes = export_sprite_probes(
        output / "OFFLINE_ONLY" / "sprite_occlusion_probes",
        map_raw,
        (assets / "johto_primary_metatiles.bin").read_bytes(),
        (assets / "johto_secondary_metatiles.bin").read_bytes(),
        (assets / "johto_primary.4bpp").read_bytes(),
    )
    assert sprite_probes["obstacle_case_count"] == 7
    assert sprite_probes["player_probe_count"] == 14
    assert not sprite_probes["sprite_overdraw_and_movement_verified_in_emulator"]
    coverage = audit_all_layers(
        output / "OFFLINE_ONLY" / "attribute_coverage",
        (assets / "johto_primary_metatiles.bin").read_bytes(),
        (assets / "johto_secondary_metatiles.bin").read_bytes(),
        (assets / "johto_primary.4bpp").read_bytes(),
    )
    assert coverage["normal_layer_candidates"] == 1012
    assert coverage["original_priority_8x8_references_checked"] == 38
    assert coverage["unresolved_behavior_words"] > 0
    assert not coverage["source_metatile_attribute_table_emitted"]
    assert all(
        coverage["metatiles"][probe["metatile_id"]]["candidate_behavior_word"] is None
        for probe in sprite_probes["cases"]
    )
    walls = export_wall_rules(
        output / "OFFLINE_ONLY" / "wall_collision_rules", coverage
    )
    assert walls["source_wall_metatiles"] == 481
    assert walls["wall_attribute_fallbacks_added"] == 0
    assert not walls["safe_for_live_registration"]
    assert all(
        wall["candidate_emerald_behavior"] is None
        for wall in walls["walls"]
    )
    water_ledge = export_water_ledge_probes(
        output / "OFFLINE_ONLY" / "water_ledge_field_probes", coverage,
        (assets / "johto_primary_metatiles.bin").read_bytes(),
        (assets / "johto_secondary_metatiles.bin").read_bytes(),
        map_raw,
    )
    assert water_ledge["source_water_metatiles"] == 59
    assert water_ledge["water_behavior_candidate_from_existing_audit"] == "MB_JOHTO_WATER"
    assert water_ledge["source_cardinal_ledge_metatiles"] == 15
    assert water_ledge["source_diagonal_ledge_metatiles"] == 4
    assert len(water_ledge["offline_map_variants"]) == 6
    assert water_ledge["native_engine_audit"]["corner_ledge_cardinal_compatibility_supported_in_engine"]
    assert not water_ledge["diagonal_ledges_require_new_engine_logic"]
    assert not water_ledge["safe_to_enable"]
    shoreline = export_surf_shoreline(
        output / "OFFLINE_ONLY" / "surf_shoreline_probes", coverage,
        (assets / "johto_primary_metatiles.bin").read_bytes(),
        (assets / "johto_secondary_metatiles.bin").read_bytes(),
        map_raw,
    )
    assert shoreline["source_water_quadrants"] == 59
    assert shoreline["candidate_generic_johto_behavior"] == "MB_JOHTO_WATER"
    assert len(shoreline["variants"]) == 4
    assert shoreline["engine_and_original_surf_permissions"]["native_surf_entry_exit_gates_verified"]
    assert not shoreline["safe_to_enable"]
    extended = export_extended_behaviors(
        output / "OFFLINE_ONLY" / "extended_behavior_review", coverage,
        (assets / "johto_primary_metatiles.bin").read_bytes(),
        (assets / "johto_secondary_metatiles.bin").read_bytes(),
    )
    assert extended["candidate_metatiles"] == 465
    assert extended["existing_basic_candidates_retained"] == 329
    assert extended["new_water_candidates"] == 59
    assert extended["new_ledge_candidates"] == 19
    assert extended["new_headbutt_tree_candidates"] == 58
    assert extended["headbutt_field_move_scripts_pending"]
    assert extended["unresolved_metatiles"] == 547
    assert extended["unresolved_wall_metatiles"] == 481
    assert not extended["safe_to_register"]
    permissions = export_wall_permissions(
        output / "OFFLINE_ONLY" / "source_wall_permissions", coverage,
        walls, extended,
    )
    assert permissions["source_wall_permission_count"] == 569
    assert permissions["existing_wall_subset_count"] == 481
    assert permissions["new_wall_permission_quadrants"] == 88
    assert not permissions["safe_to_register"]
    headbutt = export_headbutt(
        output / "OFFLINE_ONLY" / "headbutt_field_probes", coverage,
        extended, permissions, map_raw,
        (assets / "johto_primary_metatiles.bin").read_bytes(),
        (assets / "johto_secondary_metatiles.bin").read_bytes(),
    )
    assert headbutt["source_headbutt_quadrants"] == 58
    assert headbutt["facing_direction_probe_count"] == 4
    assert not headbutt["field_move_script_implemented"]
    assert not headbutt["safe_to_register"]
    assert (root / "map.bin").read_bytes() == map_raw
    (output / "OFFLINE_ONLY" / "layout_entry.review.json").write_text(
        json.dumps(proposed_layout, indent=2) + "\n", encoding="utf-8")
    (output / "OFFLINE_ONLY" / "map_header.INCOMPLETE.review.json").write_text(
        json.dumps(header, indent=2) + "\n", encoding="utf-8")

    manifest = {
        "status": "offline_package_NOT_FOR_ROM",
        "source_layout_version": "emerald",
        "map_id": MAP_ID, "layout_id": ID,
        "map_sha256": hashlib.sha256(map_raw).hexdigest(),
        "border_sha256": hashlib.sha256(border_raw).hexdigest(),
        "map_bytes": len(map_raw), "border_bytes": len(border_raw),
        "tileset_source_bundle_staged": True,
        "test_metatile_binding_count": bindings["binding_count"],
        "test_metatile_bindings_sha256": bindings["binary_sha256"],
        "test_metatile_geometry_verified": bindings["source_geometry_bytes_verified"],
        "test_metatile_bindings_live_usable": False,
        "obstacle_collision_review_sha256": obstacle_review["review_map_sha256"],
        "obstacle_collision_review_cells": obstacle_review["changed_cells"],
        "obstacle_collision_review_offline_only": True,
        "obstacle_foreground_subtiles_checked": layer_review["source_8x8_subtiles_checked"],
        "obstacle_priority_source_flags_verified": layer_review["source_bit7_priority_references_matched"],
        "obstacle_bg1_bg2_source_conversion_verified": layer_review["masked_bg1_graphics_matched"],
        "obstacle_sprite_occlusion_verified_in_emulator": False,
        "sprite_occlusion_probe_cases": sprite_probes["obstacle_case_count"],
        "sprite_occlusion_probe_positions": sprite_probes["player_probe_count"],
        "sprite_occlusion_priority_cases": sprite_probes["priority_mask_case_count"],
        "sprite_occlusion_probe_map_sha256": sprite_probes["probe_map_sha256"],
        "sprite_occlusion_probe_registered": False,
        "all_johto_layer_candidates_verified": coverage["normal_layer_candidates"],
        "all_johto_source_priority_tiles_verified": coverage["original_priority_8x8_references_checked"],
        "johto_known_behavior_candidates": coverage["known_behavior_word_candidates"],
        "johto_unresolved_behavior_words": coverage["unresolved_behavior_words"],
        "full_johto_attribute_table_emitted": False,
        "source_wall_collision_rule_count": walls["source_wall_metatiles"],
        "wall_collision_rule_binary_sha256": walls["review_binary_sha256"],
        "wall_collision_rule_engine_gate_checked": walls["movement_gate_checked_against_native_engine"],
        "wall_attribute_fallbacks_added": walls["wall_attribute_fallbacks_added"],
        "wall_collision_rules_registered": False,
        "water_ledge_metatiles_reviewed": water_ledge["source_metatiles_checked"],
        "water_ledge_probe_variants": len(water_ledge["offline_map_variants"]),
        "water_ledge_cardinal_count": water_ledge["source_cardinal_ledge_metatiles"],
        "water_ledge_diagonal_blocked_count": 0,
        "water_ledge_corner_source_count": water_ledge["source_diagonal_ledge_metatiles"],
        "water_ledge_corner_dispatch_source_verified": water_ledge["corner_ledge_source_facing_masks_verified"],
        "water_ledge_behavior_attributes_registered": False,
        "surf_shoreline_probe_variants": len(shoreline["variants"]),
        "surf_shoreline_source_water_quadrants": shoreline["source_water_quadrants"],
        "surf_shoreline_original_source_permissions_checked":
            shoreline["engine_and_original_surf_permissions"]["source_water_and_land_permissions_verified"],
        "surf_shoreline_pond_ocean_movement_flags_checked":
            shoreline["engine_and_original_surf_permissions"]["pond_ocean_basic_movement_and_encounter_flags_equivalent"],
        "surf_shoreline_generic_johto_water_behavior_source_checked":
            shoreline["engine_and_original_surf_permissions"]["generic_johto_surf_fishing_and_encounter_flags_verified"],
        "surf_shoreline_generic_visual_effects_deferred":
            shoreline["engine_and_original_surf_permissions"]["generic_johto_water_visual_effects_not_assumed"],
        "surf_shoreline_registered": False,
        "extended_behavior_review_pairs": extended["candidate_metatiles"],
        "extended_behavior_review_unresolved": extended["unresolved_metatiles"],
        "extended_behavior_review_pair_sha256": extended["pairs_binary_sha256"],
        "extended_behavior_review_bitmap_sha256": extended["validity_bitmap_sha256"],
        "extended_behavior_review_registered": False,
        "source_wall_permission_count": permissions["source_wall_permission_count"],
        "source_wall_permission_additional_count": permissions["new_wall_permission_quadrants"],
        "source_wall_permission_review_sha256": permissions["binary_sha256"],
        "source_wall_permission_registered": False,
        "headbutt_tree_source_quadrants": headbutt["source_headbutt_quadrants"],
        "headbutt_field_probe_count": headbutt["facing_direction_probe_count"],
        "headbutt_field_probe_sha256": headbutt["probe_map_sha256"],
        "headbutt_field_move_registered": False,
        "map_header_draft_schema_checked": True,
        "verified_header_constants": constants,
        "temporary_region_map_placeholder": region_placeholder,
        "header_without_null_field_values": True,
        "unresolved_header_fields": list(MISSING_HEADER_FIELDS),
        "debug_spawn_candidate_validated_offline": True,
        "no_warp_or_access_route": True,
        "full_tileset_attributes_ready": False,
        "visual_and_runtime_collision_verified": False,
        "map_registered": False,
        "tilesets_registered": False,
        "safe_to_enable": False,
    }
    (output / "OFFLINE_ONLY" / "package_manifest.json").write_text(
        json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return manifest

if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, required=True)
    manifest = stage(parser.parse_args().output)
    print(f"PASS: {manifest['map_bytes']}-byte map and {manifest['border_bytes']}-byte border staged")
    print("OFFLINE ONLY: Johto region-map placement unresolved; no live registration or emulator proof")
