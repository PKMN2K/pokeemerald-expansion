#!/usr/bin/env python3
"""Import Counter/Mirror Coat accuracy from the pinned default source."""
import argparse
import json

import build_pokemon_learnsets as source


def build():
    files = source.sources()
    rows = {}
    for line in source.default_lines(files['data/moves/moves.asm']):
        if line.startswith(('move COUNTER,', 'move MIRROR_COAT,')):
            name, effect, power, type_, accuracy, pp, chance, category = [x.strip() for x in line[5:].split(',')]
            assert (effect, power, accuracy, pp, chance) == ('EFFECT_COUNTER', '1', '-1', '20', '0')
            rows[name] = dict(type=type_, category=category, accuracy=int(accuracy), pp=int(pp))
    assert rows == {'COUNTER': dict(type='FIGHTING', category='PHYSICAL', accuracy=-1, pp=20),
                    'MIRROR_COAT': dict(type='PSYCHIC', category='SPECIAL', accuracy=-1, pp=20)}
    commands = files['engine/battle/effect_commands.asm']
    checkhit = commands.split('BattleCommand_checkhit:', 1)[1].split('\n.Miss:', 1)[0]
    assert 'cp EFFECT_COUNTER\n\tret z' in checkhit
    assert checkhit.index('cp EFFECT_COUNTER') < checkhit.index('; Now doing usual accuracy check')
    script = files['data/moves/effects.asm'].split('\nCounter:\n', 1)[1].split('\nEncore:', 1)[0]
    assert '\tcheckhit ; needed for Parental Bond, it can\'t miss\n\tcounter\n' in script
    counter = files['engine/battle/move_effects/counter.asm']
    assert 'call BattleCommand_resettypematchup' in counter
    assert 'call HasOpponentDamagedUs\n\tret z' in counter
    assert 'ld a, 1 << PHYSICAL' in counter and 'ld a, 1 << SPECIAL' in counter
    assert 'ld a, [hl]\n\tadd a\n\tld [hld], a' in counter
    assert 'ld a, $ff\n\tld [hli], a\n\tld [hl], a' in counter
    for path in ('engine/pokemon/summary/green_page.asm', 'engine/pokemon/mon_menu.asm'):
        display = files[path].split('ld hl, Moves + MOVE_ACC', 1)[1]
        assert ('cp -1\n\tjr nc, .no_acc' in display
                or 'cp 255\n\tjr z, .no_acc' in display)
    banner = f'/* Generated by build_retaliation_accuracy.py from Polished Crystal {source.PIN}. */\n'
    header = banner + '''#ifndef GUARD_CONSTANTS_POLISHED_RETALIATION_H
#define GUARD_CONSTANTS_POLISHED_RETALIATION_H

// Source -1 and target 0 both mean bypass the ordinary accuracy roll.
#define POLISHED_COUNTER_ACCURACY 0
#define POLISHED_MIRROR_COAT_ACCURACY 0

#endif
'''
    manifest = dict(source_repository='Rangi42/polishedcrystal', source_commit=source.PIN,
        source_variant='default (FAITHFUL undefined)', moves=rows,
        accuracy_adapter='Source -1 / EFFECT_COUNTER bypass maps to target accuracy 0.',
        scope='Accuracy/evasion/item bypass and displayed accuracy, with ordinary singles retaliation regression checks.',
        retained_runtime='EFFECT_REFLECT_DAMAGE: physical/special category masks and 200 percent damage.',
        gaps=['Full source retaliation behavior is not certified by this accuracy suite: multi-hit/Parental Bond, damage saturation, move-state bookkeeping, unusual target/protection interactions and smart AI scoring still need dedicated audits.',
              'Original source animation, UI art/layout, general damage rules and item/ability timing remain open.',
              'Expansion-only double battles and moves retain native rules.'])
    return {source.ROOT/'include/constants/polished_retaliation.h': header,
            source.ROOT/'tools/polished_port/manifests/retaliation_accuracy.json': json.dumps(manifest, indent=2)+'\n'}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, expected in build().items():
        if args.check:
            assert path.read_text() == expected, f'Regenerate {path}'
        else:
            path.write_text(expected)
    print('PASS: pinned Counter/Mirror Coat accuracy bypass and explicit source scope')
