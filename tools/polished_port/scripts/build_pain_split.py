#!/usr/bin/env python3
"""Import the pinned default Pain Split row and source HP-sharing fixtures."""
import argparse
import json

import build_pokemon_learnsets as source


def share(user, user_max, target, target_max):
    # Follow source subtraction/restoration, independently of the GBA average.
    if user > target:
        delta = user - target
        user -= (delta + 1) // 2
        target = min(target_max, target + delta // 2)
    elif target > user:
        delta = target - user
        target -= (delta + 1) // 2
        user = min(user_max, user + delta // 2)
    return user, target


def build():
    files = source.sources()
    row = next(line for line in source.default_lines(files['data/moves/moves.asm']) if line.startswith('move PAIN_SPLIT,'))
    assert [x.strip() for x in row[5:].split(',')] == ['PAIN_SPLIT', 'EFFECT_PAIN_SPLIT', '0', 'GHOST', '-1', '20', '0', 'STATUS']
    effect = files['engine/battle/move_effects/pain_split.asm']
    commands = files['engine/battle/effect_commands.asm']
    script = files['data/moves/effects.asm'].split('\nPainSplit:\n', 1)[1].split('\nSketch:', 1)[0]
    assert '\tcheckhit\n\tcheckpriority\n\tpainsplit\n\tendmove' in script
    assert 'failuretext' not in script
    assert 'call CheckHiddenOpponent\n\tjr nz, .failed' in effect
    assert 'srl b\n\trr c\n\tpush bc\n\tjr nc, .even_share\n\tinc bc' in effect
    assert effect.index('predef SubtractHPFromUser') < effect.index('farcall RestoreHP')
    assert 'call SwitchTurn\n\tcall .share\n\tjmp SwitchTurn' in effect
    assert 'wAttackMissed' not in effect and 'CheckSubstituteOpp' not in effect
    hidden = commands.split('\nCheckHiddenOpponent:\n', 1)[1].split('\nGetPlayerItem::', 1)[0]
    assert 'and 1 << SUBSTATUS_FLYING | 1 << SUBSTATUS_UNDERGROUND' in hidden
    substitute = commands.split('\n.Substitute:\n', 1)[1].split('\n.LockOn:', 1)[0]
    assert 'cp SWAGGER' in substitute and 'cp EFFECT_TRAP' in substitute
    assert 'PAIN_SPLIT' not in substitute
    miss = commands.split('\n.Miss_skipset:\n', 1)[1].split('\n.DreamEater:', 1)[0]
    assert 'ld [wAttackMissed], a' in miss and 'EndMoveEffect' not in miss
    interpreter = commands.split('\n.ReadMoveEffectCommand:\n', 1)[1].split('\n.endturn_herb', 1)[0]
    assert 'call _hl_' in interpreter and 'wAttackMissed' not in interpreter

    pairs = [(1, 1), (1, 2), (2, 1), (1, 3), (3, 1), (10, 100),
             (100, 10), (10, 101), (101, 10), (55, 55), (254, 255),
             (255, 254), (255, 256), (256, 255), (1023, 511), (511, 1023)]
    cases = [(a, 1200, b, 1200) for a, b in pairs]
    cases += [(20, 30, 180, 200), (180, 200, 20, 30), (30, 30, 180, 200),
              (180, 200, 30, 30), (1, 1, 256, 300), (256, 300, 1, 1)]
    records = [dict(user_hp=a, user_max=am, target_hp=b, target_max=bm,
                    result=list(share(a, am, b, bm))) for a, am, b, bm in cases]
    # Exhaustively establish equivalence of the retained average on byte-sized
    # HP, plus fixtures crossing byte boundaries and saturating each max HP.
    for a in range(1, 256):
        for b in range(1, 256):
            assert share(a, 255, b, 255) == ((a + b) // 2,) * 2

    banner = f'/* Generated by build_pain_split.py from Polished Crystal {source.PIN}. */\n'
    header = banner + '''#ifndef GUARD_CONSTANTS_POLISHED_PAIN_SPLIT_H
#define GUARD_CONSTANTS_POLISHED_PAIN_SPLIT_H

#define POLISHED_PAIN_SPLIT_TYPE TYPE_GHOST
#define POLISHED_PAIN_SPLIT_ACCURACY 0

#endif
'''
    fixtures = banner + '''static const struct PainSplitCase
{
    u16 playerHP, playerMaxHP, opponentHP, opponentMaxHP;
    u16 playerResult, opponentResult;
} sPainSplitCases[] =
{
'''
    fixtures += ''.join('    {' + ', '.join(map(str, [*case, *share(*case)])) + '},\n' for case in cases)
    fixtures += '};\n'
    manifest = dict(source_repository='Rangi42/polishedcrystal', source_commit=source.PIN,
        source_variant='default (FAITHFUL undefined)', type='GHOST', accuracy='-1 mapped to target 0',
        power=0, pp=20, category='STATUS', bypasses_substitute=True, bypasses_protect=True,
        bypass_explanation='The hit check records failure, but the Pain Split command does not consume wAttackMissed; there is no failuretext command in this effect script.',
        hidden_target_rule='Fly/Dig fail even after No Guard or Lock-On bypasses the general hit check.',
        hp_rule='Subtract ceil(difference/2) from the healthier battler first; restore floor(difference/2) to the other, capped at its max HP.',
        cases=records,
        gaps=['Native animation, dialogue, general accuracy RNG and ability/item interaction timing remain separately audited.',
              'Source-specific smart AI scoring is not imported here; shared target gates are available to native AI.',
              'Optional Expansion-only gimmicks retain their native adapters.'])
    return {source.ROOT/'include/constants/polished_pain_split.h': header,
            source.ROOT/'include/test/polished_pain_split_cases.h': fixtures,
            source.ROOT/'tools/polished_port/manifests/pain_split.json': json.dumps(manifest, indent=2)+'\n'}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, expected in build().items():
        if args.check:
            assert path.read_text() == expected, f'Regenerate {path}'
        else:
            path.write_text(expected)
    print('PASS: pinned Pain Split type, target gates, source HP arithmetic and 22 boundary fixtures')
