#!/usr/bin/env python3
"""Import listed accuracy for Dragon Dance and Sleep Talk without adding hit rolls."""
import argparse
import json

import build_pokemon_learnsets as source


def build():
    files = source.sources()
    rows = {}
    for line in source.default_lines(files['data/moves/moves.asm']):
        if line.startswith(('move DRAGON_DANCE,', 'move SLEEP_TALK,')):
            name, effect, power, type_, accuracy, pp, chance, category = [v.strip() for v in line[5:].split(',')]
            assert power == chance == '0' and accuracy == '100' and category == 'STATUS'
            rows[name] = dict(effect=effect, type=type_, accuracy=int(accuracy), pp=int(pp))
    assert rows == {'DRAGON_DANCE': dict(effect='EFFECT_DRAGON_DANCE', type='DRAGON', accuracy=100, pp=20),
                    'SLEEP_TALK': dict(effect='EFFECT_SLEEP_TALK', type='NORMAL', accuracy=100, pp=10)}
    effects = files['data/moves/effects.asm']
    dance = effects.split('\nDragonDance:\n', 1)[1].split('\nHoneClaws:', 1)[0]
    talk = effects.split('\nSleepTalk:\n', 1)[1].split('\nDestinyBond:', 1)[0]
    assert '\tforceraisestat ATTACK\n\tforceraisestat SPEED\n' in dance
    assert '\tsleeptalk\n\tendmove' in talk
    assert 'checkhit' not in dance and 'checkhit' not in talk
    command = files['engine/battle/move_effects/sleep_talk.asm']
    assert 'and SLP_MASK\n\tjr z, .fail' in command
    assert 'ld a, c\n\tand a\n\tjr z, .fail' in command
    assert 'call UpdateMoveData' in command and '\tjmp ResetTurn' in command
    for path in ('engine/pokemon/summary/green_page.asm', 'engine/pokemon/mon_menu.asm'):
        display = files[path].split('ld hl, Moves + MOVE_ACC', 1)[1].split('.description', 1)[0]
        assert 'call PrintNum' in display
    banner = f'/* Generated by build_self_move_accuracy.py from Polished Crystal {source.PIN}. */\n'
    header = banner + '#ifndef GUARD_CONSTANTS_POLISHED_SELF_MOVE_ACCURACY_H\n#define GUARD_CONSTANTS_POLISHED_SELF_MOVE_ACCURACY_H\n\n'
    header += '// These listed values do not create an accuracy roll for the parent effect.\n'
    header += ''.join(f'#define POLISHED_{name}_ACCURACY {row["accuracy"]}\n' for name, row in rows.items())
    header += '\n#endif\n'
    manifest = dict(source_repository='Rangi42/polishedcrystal', source_commit=source.PIN,
        source_variant='default (FAITHFUL undefined)', moves=rows,
        selection='Existing B_POLISHED_MOVE_BALANCE / POLISHED_BALANCE compile-time data profile.',
        scope='Listed accuracy, parent AI accuracy estimates and ordinary self-effect/called-move hit-check regression coverage.',
        runtime_contract=['Dragon Dance raises user Attack and Speed without an accuracy check.',
                          'Sleep Talk replaces current move data and restarts move execution; the called move uses its own hit rules.',
                          'The native AI represents both parent effects with its accuracy-bypass sentinel; their numeric listing must not introduce a miss estimate.'],
        gaps=['This does not certify the complete Sleep Talk eligible-move pool, disabled/encored move rules, source RNG, sleep duration, or general move-calling bookkeeping.',
              'Original animations, source UI layout/art, general stat-change/item/ability rules and smart AI scoring remain separate audits.',
              'Expansion-only mechanics retain native behavior.'])
    return {source.ROOT/'include/constants/polished_self_move_accuracy.h': header,
            source.ROOT/'tools/polished_port/manifests/self_move_accuracy.json': json.dumps(manifest, indent=2)+'\n'}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, expected in build().items():
        if args.check:
            assert path.read_text() == expected, f'Regenerate {path}'
        else:
            path.write_text(expected)
    print('PASS: pinned Dragon Dance/Sleep Talk listed accuracy and no parent hit check')
