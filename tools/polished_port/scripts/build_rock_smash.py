#!/usr/bin/env python3
"""Import pinned Dark Cave rock encounters, items, text and Brick Piece art."""
import argparse
import base64
import hashlib
import json
import re
import tempfile
from pathlib import Path
import build_pokemon_held_items as held
from convert_player_walking import _read_png_2bit_grayscale, _write_indexed_4bit_png
from polished_route30 import palette
ROOT = held.ROOT
FIXTURES = ROOT / 'tools/polished_port/fixtures/rock_smash'


def sources():
    manifest = json.loads((FIXTURES / 'sources.json').read_text())
    assert manifest['commit'] == held.source.PIN
    files = {}
    for entry in manifest['files']:
        data = base64.b64decode((FIXTURES / entry['fixture']).read_text())
        assert hashlib.sha1(b'blob ' + str(len(data)).encode() + b'\0' + data).hexdigest() == entry['git_blob_sha1']
        files[entry['path']] = data
    return files


def build():
    f = sources()
    items = [(int(w), n) for w,n in re.findall(r'\bdb (\d+), (\w+)', f['data/items/rock_items.asm'].decode())]
    body = f['data/wild/treemons.asm'].decode().split('TreeMonSet_Rock:\n')[1]
    mons = [(int(w), n, int(l)) for w,n,l in re.findall(r'tree_mon\s+(\d+),\s*(\w+),\s*(\d+)', body)]
    assert sum(w for w,n in items) == 256 and sum(w for w,n,l in mons) == 100
    engine = f['engine/events/treemons.asm'].decode().split('RockMonEncounter:',1)[1].split('GetTreeMonSet:',1)[0]
    gate = tuple(map(int,re.search(r'ld a, (\d+)\n\tcall RandomRange\n\tcp (\d+)',engine).groups()))
    assert gate == (10,4)
    mapped = lambda n: 'ITEM_' + {'BRICK_PIECE':'POLISHED_BRICK_PIECE','NO_ITEM':'NONE'}.get(n,n)
    lines = ['/* Generated by build_rock_smash.py from pinned default Polished Crystal. */',f'#define POLISHED_ROCK_GATE_RANGE {gate[0]}',f'#define POLISHED_ROCK_GATE_HITS {gate[1]}','static const struct RockMon sRockMons[] = {']
    lines += [f'    {{{w}, SPECIES_{n}, {l}}},' for w,n,l in mons]
    lines += ['};','static const struct RockItem sRockItems[] = {']
    lines += [f'    {{{w}, {mapped(n)}}},' for w,n in items]
    lines += ['};','']
    result = {ROOT/'src/data/polished_rock_smash.h':'\n'.join(lines).encode()}
    h=held.sources(); data=held.catalog(h)['BRICK_PIECE']; index=data['source_id']
    assert index == 239 and data['source_attributes'] == ['100','0','0','ITEM','ITEMMENU_NOUSE','ITEMMENU_NOUSE']
    pointers=re.findall(r'\bdba (\w+)',h['data/items/icon_pointers.asm'].decode().split('assert_table_length NUM_ITEMS')[0])
    assert pointers[index]=='BrickPieceIcon'
    assert 'BrickPieceIcon:: INCBIN "gfx/items/brick_piece.2bpp.lz"' in h['gfx/items.asm'].decode()
    colors=[tuple(map(int,m)) for m in re.findall(r'RGB\s+(\d+),\s*(\d+),\s*(\d+)',h['gfx/items/items.pal'].decode().split('else')[0])][index*2:index*2+2]
    with tempfile.TemporaryDirectory() as tmp:
        src,out=Path(tmp)/'src.png',Path(tmp)/'out.png'
        src.write_bytes(f['gfx/items/brick_piece.png']); w,hgt,pixels=_read_png_2bit_grayscale(src)
        assert (w,hgt)==(24,24)
        _write_indexed_4bit_png(out,[[3-p for p in row] for row in pixels])
        result[ROOT/'graphics/items/icons/polished_brick_piece.png']=out.read_bytes()
    result[ROOT/'graphics/items/icon_palettes/polished_brick_piece.pal']=palette(colors)
    result[ROOT/'src/data/polished_rock_smash_item.h'] = ('''/* Generated source Brick Piece identity; existing item IDs are unchanged. */
    [ITEM_POLISHED_BRICK_PIECE] =
    {
        .name = ITEM_NAME("%s"),
        .pluralName = ITEM_PLURAL_NAME("%s"),
        .price = 100,
        .description = COMPOUND_STRING("%s"),
        .pocket = POCKET_ITEMS,
        .type = ITEM_USE_BAG_MENU,
        .fieldUseFunc = ItemUseOutOfBattle_CannotUse,
        .iconPic = gItemIcon_PolishedBrickPiece,
        .iconPalette = gItemIconPalette_PolishedBrickPiece,
    },
''' % (data['source_name'],held.plural_name(h,data['source_name']),data['source_description'])).encode()
    texts=f['data/text/common.asm'].decode()
    assert '.Item:\n\tdb "Item Pocket@"' in f['data/items/pocket_names.asm'].decode()
    assert all(n=='NO_ITEM' or held.catalog(h)[n]['source_attributes'][3]=='ITEM' for w,n in items)
    text_lines=['@ Generated default-source rock dialogue.']
    for name,target in [('UseRockSmash','Used'),('MaySmash','Unavailable'),('AskRockSmash','Ask'),('GainedItem','Gained'),('PutItemInPocket','PutAway'),('PocketIsFull','Full')]:
        body='\n'.join(held.source.default_lines(texts.split('_'+name+'Text::',1)[1].split('\n_',1)[0]))
        parts=[]
        for op,content in re.findall(r'^\s*(text_ram|text|line|para|cont) (.*)$',body,re.M):
            if op=='text_ram':
                parts.append({'wStringBuffer2':'{STR_VAR_1}', 'wStringBuffer4':'{STR_VAR_2}', 'wStringBuffer1':'{STR_VAR_2}', 'wStringBuffer3':'Item Pocket'}[content])
            else: parts.append({'text':'','line':'\\n','para':'\\p','cont':'\\l'}[op]+content.strip('"').replace('#mon','POKéMON').replace('<PLAYER>','{PLAYER}').replace('…','...'))
        text_lines += ['PolishedRockSmash_'+target+'Text:', '    .string "'+''.join(parts)+'$"']
    result[ROOT/'data/text/polished_rock_smash.inc']=('\n'.join(text_lines)+'\n').encode()
    manifest=dict(source_commit=held.source.PIN,source_variant='default; FAITHFUL undefined',map='MAP_POLISHED_DARK_CAVE_VIOLET_ENTRANCE',battle_gate=dict(range=gate[0],hits=gate[1]),encounters=[dict(weight=w,species='SPECIES_'+n,level=l) for w,n,l in mons],items=[dict(weight=w,source=n,target=mapped(n)) for w,n in items],brick_piece=dict(target_id=883,source_rgb555=colors,**data),rules=['First non-Egg knower in physical party order, otherwise first source-compatible non-Egg with owned TM31; HP and badges ignored.','Recheck eligibility before auto-use; only accepted use sets map-visit active state.','Menu requires known Brick Break and uses the selected party member, without asking.','Battle gate then encounter slot OR item byte; never an item after a battle.','Warp/connection resets; battle reload and Save/Continue preserve active state and removed rocks.'],gaps=['Native Pokemon pictures/cry, Strength/item SFX and message-box styling remain presentation substitutions.','Existing mapped item properties and the broader battle/creation engine retain documented parity gaps.','Uniform GBA RNG preserves source probabilities, not the original GBC random sequence.'])
    result[ROOT/'tools/polished_port/manifests/rock_smash.json']=(json.dumps(manifest,indent=2)+'\n').encode()
    return result


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');args=p.parse_args()
    for path,data in build().items():
        if args.check: assert path.exists() and path.read_bytes()==data, f'Regenerate {path}'
        else: path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(data)
    print('PASS: pinned rock encounters, rewards, dialogue and Brick Piece icon')
if __name__=='__main__': main()
