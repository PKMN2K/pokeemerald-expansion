#!/usr/bin/env python3
"""Build the mapped source bag icons and Giovanni's trainer portrait."""
import argparse
import hashlib
from pathlib import Path
import re
import struct
import subprocess
import tempfile
import zipfile

from build_pokemon_held_items import ALIASES, ROOT, catalog, sources
from build_item_prices import FACILITY_PRIZES, MART_ALIASES
from build_pokemon_learnsets import PIN
from convert_player_walking import _read_png_2bit_grayscale, _write_indexed_4bit_png
from polished_route30 import palette

ARCHIVE = ROOT / 'tools/polished_port/fixtures/battle_art.zip'
ARCHIVE_SHA256 = 'e8256122df1c937cf8b6306454a87dea5349fb533250adb9173dcf2cee0dd6ed'
PICTURES = ROOT / 'graphics/items/icons/polished_battle_icons.bin'
TABLE = ROOT / 'src/data/polished_battle_icons.h'
ALIASED_ITEMS = {
    **ALIASES, **{s: pair[0].removeprefix('ITEM_') for s, pair in (MART_ALIASES | FACILITY_PRIZES).items()},
    'PEWTERCRUNCH': 'PEWTER_CRUNCHIES', 'MULCH': 'POLISHED_MULCH', 'SWEET_HONEY': 'HONEY',
    'ABILITY_CAP': 'ABILITY_CAPSULE', 'METRONOME_I': 'METRONOME', 'WEAK_POLICY': 'WEAKNESS_POLICY',
    'SAFE_GOGGLES': 'SAFETY_GOGGLES', 'PROTECT_PADS': 'PROTECTIVE_PADS', 'HEAVY_BOOTS': 'HEAVY_DUTY_BOOTS',
    'BLUNDRPOLICY': 'BLUNDER_POLICY', 'PUNCHINGLOVE': 'PUNCHING_GLOVE', 'ARMOR_SUIT': 'POLISHED_ARMOR_SUIT',
    'ODD_SOUVENIR': 'POLISHED_ODD_SOUVENIR', 'BRICK_PIECE': 'POLISHED_BRICK_PIECE',
}
# These source items currently have no corresponding ordinary GBA item.
UNBOUND = set('SLOWPOKETAIL SURF_MAIL LITEBLUEMAIL PORTRAITMAIL LOVELY_MAIL EON_MAIL MORPH_MAIL BLUESKY_MAIL MUSIC_MAIL MIRAGE_MAIL'.split())


def mapping():
    files = sources()
    items = catalog(files)
    ids = re.findall(r'^\s*ITEM_(\w+)\s*(?:=|,)', (ROOT/'include/constants/items.h').read_text(), re.M)
    spellings = {key.replace('_', ''): key for key in ids}
    pointers = re.findall(r'\bdba (\w+)', files['data/items/icon_pointers.asm'].decode().split('assert_table_length', 1)[0])
    graphic_index = files['gfx/items.asm'].decode()
    rows = []
    color_data = files['gfx/items/items.pal'].decode().split('else', 1)[0]
    colors = [tuple(map(int, m)) for m in re.findall(r'RGB\s+(\d+),\s*(\d+),\s*(\d+)', color_data)]
    assert len(colors) == len(pointers) * 2 == 510
    for name, row in items.items():
        target = ALIASED_ITEMS.get(name, spellings.get(name.replace('_', '')))
        if not target:
            assert name in UNBOUND, name
            continue
        assert target in ids and name not in UNBOUND, (name, target)
        index = row['source_id']
        label = pointers[index]
        path = re.search(r'INCBIN "([^"]+)\.2bpp\.lz"', graphic_index.split(label+'::', 1)[1])[1]+'.png'
        rows.append((name, 'ITEM_'+target, path, colors[2*index:2*index+2]))
    assert len(rows) == len(items) - len(UNBOUND) and len({row[1] for row in rows}) == len(rows)
    assert len(rows) <= 255
    return rows


def tile_bytes(pixels):
    return bytes((3 - pixels[y+j][x+i]) | (3 - pixels[y+j][x+i+1]) << 4
                 for y in range(0, len(pixels), 8) for x in range(0, len(pixels[0]), 8)
                 for j in range(8) for i in range(0, 8, 2))


def build():
    rows = mapping()
    image_paths = {row[2] for row in rows} | {'gfx/trainers/giovanni.png', 'gfx/trainers/giovanni.pal'}
    assert hashlib.sha256(ARCHIVE.read_bytes()).hexdigest() == ARCHIVE_SHA256
    with tempfile.TemporaryDirectory() as tmp, zipfile.ZipFile(ARCHIVE) as archive:
        tmp = Path(tmp)
        assert set(archive.namelist()) == image_paths
        src = tmp/'original.png'
        tiles = tmp/'tiles.bin'
        compressed = tmp/'tiles.lz'
        chunks = bytearray()
        offsets = {}
        table = ['/* Generated by build_battle_art.py from the pinned default source. */',
                 'static const u8 sPolishedIconIndex[ITEMS_COUNT] = {']
        table += [f'    [{row[1]}] = {i},' for i, row in enumerate(rows, 1)]
        table += ['};', 'static const struct PolishedItemIcon sPolishedItemIcons[] = {', '    {0},']
        cases = []
        for name, target, path, shades in rows:
            src.write_bytes(archive.read(path))
            w, h, pixels = _read_png_2bit_grayscale(src)
            assert (w, h) == (24, 24)
            raw = tile_bytes(pixels)
            if path not in offsets:
                tiles.write_bytes(raw)
                subprocess.run([ROOT/'tools/gbagfx/gbagfx', tiles, compressed], check=True)
                offsets[path] = len(chunks)
                chunks.extend(compressed.read_bytes())
                chunks.extend(bytes(-len(chunks) % 4))
            colors = [0x7fff] + [r | g << 5 | b << 10 for r, g, b in shades] + [0]*13
            table.append(f'    {{{offsets[path]//4}, {{0x7fff, 0x{colors[1]:04x}, 0x{colors[2]:04x}}}}}, /* {name} */')
            cases.append((target, raw, struct.pack('<16H', *colors)))
        table += ['};', '']
        src.write_bytes(archive.read('gfx/trainers/giovanni.png'))
        w, h, pixels = _read_png_2bit_grayscale(src)
        assert (w, h) == (56, 56)
        canvas = [[0]*64 for _ in range(64)]
        for y, row in enumerate(pixels):
            canvas[8+y][4:60] = [3-v for v in row]
        out = tmp/'portrait.png'
        _write_indexed_4bit_png(out, canvas)
        shades = [tuple(map(int, m)) for m in re.findall(r'RGB\s+(\d+),\s*(\d+),\s*(\d+)', archive.read('gfx/trainers/giovanni.pal').decode())]
        assert len(shades) == 2
        portrait = (tile_bytes([[3-v for v in row] for row in canvas]),
                    struct.pack('<16H', 0x7fff, *[r | g << 5 | b << 10 for r,g,b in shades], *([0]*13)))
        outputs = {PICTURES: bytes(chunks), TABLE: '\n'.join(table).encode(),
                   ROOT/'graphics/trainers/front_pics/polished_giovanni.png': out.read_bytes(),
                   ROOT/'graphics/trainers/palettes/polished_giovanni.pal': palette(shades)}
        return outputs, cases, portrait


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--source-root', type=Path, help='Verify every imported image against the pinned Git commit')
    args = ap.parse_args()
    if args.source_root:
        with zipfile.ZipFile(ARCHIVE) as archive:
            for name in archive.namelist():
                data = subprocess.check_output(['git', '-C', args.source_root, 'show', PIN+':'+name])
                assert archive.read(name) == data, name
    outputs, cases, _ = build()
    for path, content in outputs.items():
        if args.check:
            assert path.read_bytes() == content, path
        else:
            path.write_bytes(content)
    print(f'PASS: {len(cases)} ordinary source item icons and the Giovanni trainer portrait')
