#!/usr/bin/env python3
"""Import all pinned default move PP values and the source PP Up calculation."""
import argparse
import json
import re

import build_pokemon_learnsets as source

TABLE = source.ROOT / "src/data/polished_move_pp.h"
CONSTANTS = source.ROOT / "include/constants/polished_move_pp.h"
MANIFEST = source.ROOT / "tools/polished_port/manifests/move_pp.json"


def build():
    files = source.sources()
    rows = [[part.strip() for part in line[5:].split(",")] for line in
            source.default_lines(files["data/moves/moves.asm"].split("Moves::", 1)[1])
            if line.startswith("move ")]
    move_constants = "\n".join(source.default_lines(
        files["constants/move_constants.asm"].split("DEF NUM_ATTACKS", 1)[0]))
    ids = re.findall(r"^const (\w+)", move_constants, re.M)
    # The default build names source ID 249 Brick Break; ROCK_SMASH is its
    # original constant name, not the native target's different Rock Smash move.
    aliases = dict(re.findall(r"^DEF (\w+) EQU (\w+)$", move_constants, re.M))
    assert aliases == {"BRICK_BREAK": "ROCK_SMASH"}
    assert ids == ["NO_MOVE"] + [aliases.get(row[0], row[0]) for row in rows]
    assert len(rows) == 255 and len(set(ids)) == 256
    available = set(re.findall(r"\bMOVE_\w+", (source.ROOT / "include/constants/moves.h").read_text()))
    effects = files["engine/items/item_effects.asm"]
    compute = effects.split("\nComputeMaxPP:\n", 1)[1].split("\nRestoreTempPP:", 1)[0]
    divisor = int(re.search(r"ld a, (\d+)\n\tldh \[hDivisor\], a", compute)[1])
    limit, increment = [int(v, 16) for v in re.search(r"cp \$(\w+)\n\tjr c, .okay\n\tld a, \$(\w+)", compute).groups()]
    assert (divisor, limit, increment) == (5, 8, 7)
    assert "swap a\n\tand $f\n\tsrl a\n\tsrl a\n\tld c, a" in compute
    assert "add b\n\tld b, a" in compute and "dec c\n\tjr nz, .loop" in compute
    ppup = effects.split("\n.ppup2\n", 1)[1].split("\nBattleRestorePP:", 1)[0]
    assert "cp SKETCH\n\tjr z, .CantUsePPUpOnSketch" in ppup
    assert "cp 3 << 6" in ppup and "ld b, 3\n\tjr z, .pp_restore_loop\n\tld b, 1" in ppup
    maximum = effects.split("\nGetMaxPPOfMove:\n", 1)[1].split("\nGetMthMoveOfNthPartymon:", 1)[0]
    assert "ld hl, Moves + MOVE_PP\n\tcall GetMoveProperty" in maximum
    assert "call ComputeMaxPP" in maximum and "and PP_MASK" in maximum

    records = []
    for index, row in enumerate(rows, 1):
        assert len(row) == 8
        name, pp = row[0], int(row[5])
        target = "MOVE_" + source.MOVE_ALIASES.get(name, name)
        assert target in available and 1 <= pp <= 40, (name, pp, target)
        records.append(dict(source_id=index, source_constant=ids[index], source_move=name, target_move=target,
                            pp=pp, max_pp=[pp + min(pp // divisor, increment) * n for n in range(4)]))
    assert len({r["target_move"] for r in records}) == len(records)
    assert {r["source_move"] for r in records if r["pp"] == 1} == {"SKETCH", "STRUGGLE"}
    generated = f"/* Generated by build_move_pp.py from Polished Crystal {source.PIN}. */\n"
    table = generated + "const u8 gPolishedMovePP[MOVES_COUNT] = {\n"
    table += "".join(f"    [{r['target_move']}] = {r['pp']},\n" for r in records) + "};\n"
    constants = (generated + "#ifndef GUARD_CONSTANTS_POLISHED_MOVE_PP_H\n"
                 "#define GUARD_CONSTANTS_POLISHED_MOVE_PP_H\n\n"
                 f"#define POLISHED_PP_UP_DIVISOR {divisor}\n"
                 f"#define POLISHED_PP_UP_MAX_INCREMENT {increment}\n\n#endif\n")
    manifest = dict(repository="Rangi42/polishedcrystal", commit=source.PIN,
                    variant="default (FAITHFUL undefined)",
                    source_files=["data/moves/moves.asm", "constants/move_constants.asm", "engine/items/item_effects.asm"],
                    pp_up_divisor=divisor, pp_up_max_increment=increment, moves=records)
    return {TABLE: table, CONSTANTS: constants, MANIFEST: json.dumps(manifest, indent=2) + "\n"}


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, text in build().items():
        if args.check:
            assert path.read_text() == text, f"Regenerate source move PP: {path}"
        else:
            path.write_text(text)
    print("PASS: 255 source move PP mappings, default variant, PP Up increments and 40-to-61 maximum")
