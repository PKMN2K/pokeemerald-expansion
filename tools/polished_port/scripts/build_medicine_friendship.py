#!/usr/bin/env python3
"""Import bitter-medicine happiness penalties from pinned Polished Crystal."""
import argparse
import re

import build_pokemon_learnsets as source

OUTPUT = source.ROOT / "src/data/polished_medicine_friendship.h"


def build():
    files = source.sources()
    constants = files["constants/pokemon_data_constants.asm"]
    actions = constants.split("; ChangeHappiness arguments", 1)[1].split("DEF NUM_HAPPINESS_CHANGES", 1)[0]
    events = re.findall(r"^\s*const (HAPPINESS_\w+)", actions, re.M)
    rows = re.findall(r"^\s*db ([^;\n]+)", files["data/events/happiness_changes.asm"], re.M)
    changes = [[int(n.strip()) for n in row.split(",")] for row in rows]
    assert len(events) == len(changes) == 23 and all(len(row) == 3 for row in changes)
    thresholds = [int(re.search(rf"DEF HAPPINESS_THRESHOLD_{n} EQU (\d+)", constants)[1]) for n in (1, 2)]
    assert thresholds == [100, 160]
    happiness = files["engine/events/happiness_egg.asm"].split("ChangeHappiness:", 1)[1].split('INCLUDE "data/events/happiness_changes.asm"', 1)[0]
    assert "bit MON_IS_EGG_F, [hl]\n\tret nz" in happiness
    assert "cp HAPPINESS_THRESHOLD_1" in happiness and "cp HAPPINESS_THRESHOLD_2" in happiness
    negative = happiness.split("\n.negative\n", 1)[1].split("\n.done\n", 1)[0]
    assert negative.strip() == "add [hl]\n\tjr c, .done\n\txor a"
    assert "ld [wBattleMonHappiness], a" in happiness

    effects = files["engine/items/item_effects.asm"]
    handlers = re.findall(r"dw (EnergyPowder|EnergyRoot|HealPowder|RevivalHerb)\s*; (\w+)", effects)
    assert len(handlers) == 4
    common = effects.split("EnergyPowderEnergyRootCommon:", 1)[1].split("ItemRestoreHP:", 1)[0]
    assert "jmp nz, WontHaveAnyEffectMessage\n\n\tpredef ChangeHappiness" in common
    lines = [f"/* Generated by build_medicine_friendship.py from Polished Crystal {source.PIN}. */",
             f"#define POLISHED_MEDICINE_FRIENDSHIP_LOW {thresholds[0]}",
             f"#define POLISHED_MEDICINE_FRIENDSHIP_HIGH {thresholds[1]}",
             "static const struct PolishedMedicineFriendship sPolishedMedicineFriendship[] = {"]
    for handler, item in handlers:
        body = re.search(rf"^{handler}:\n(.*?)(?=^\w+:)", effects, re.M | re.S)[1]
        event = re.search(r"ld c, (HAPPINESS_\w+)", body)[1]
        if handler in ("HealPowder", "RevivalHerb"):
            assert body.index("jmp nz, WontHaveAnyEffectMessage") < body.index("predef ChangeHappiness")
        row = changes[events.index(event)]
        assert all(-128 <= n < 0 for n in row), (item, row)
        target = {"ENERGYPOWDER": "ENERGY_POWDER"}.get(item, item)
        lines.append(f"    {{ITEM_{target}, {{{', '.join(map(str, row))}}}}},")
    lines += ["};", ""]
    return "\n".join(lines).encode()


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = build()
    if args.check:
        assert OUTPUT.read_bytes() == data, "Regenerate source medicine friendship"
    else:
        OUTPUT.write_bytes(data)
    print("PASS: four source bitter medicines, 100/160 thresholds, negative clamp, egg guard and successful-use dispatch")
