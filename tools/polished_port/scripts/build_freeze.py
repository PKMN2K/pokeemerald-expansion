#!/usr/bin/env python3
"""Pin the source natural-thaw byte threshold and absence of a freeze timer."""
import argparse
import json

import build_pokemon_learnsets as source


def build():
    files = source.sources()
    assert 'DEF percent EQUS "* $ff / 100"' in files['macros/data.asm']
    commands = files['engine/battle/effect_commands.asm']
    block = commands.split('\n.not_asleep\n', 1)[1].split('\n.not_frozen\n', 1)[0]
    assert [line for line in source.default_lines(block) if line] == [
        'ld a, BATTLE_VARS_STATUS', 'call GetBattleVarAddr', 'bit FRZ, [hl]',
        'jr z, .not_frozen', 'ld a, BATTLE_VARS_MOVE_ANIM', 'call GetBattleVar',
        'cp SACRED_FIRE', 'jr z, .thaw', 'cp SCALD', 'jr z, .thaw',
        'cp FLARE_BLITZ', 'jr z, .thaw', 'call BattleRandom', 'cp 1 + (20 percent)',
        'jr c, .thaw', 'ld hl, FrozenSolidText', 'call StdBattleTextbox', 'xor a',
        'ld [wNumHits], a', 'ld de, ANIM_FRZ', 'call FarPlayBattleAnimation',
        'call CantMove', 'jmp EndTurn', '.thaw', 'call DefrostUser']
    defrost = commands.split('\nDefrostUser:', 1)[1].split('\nCheckAlreadyExecuted:', 1)[0]
    assert [line for line in source.default_lines(defrost) if line] == [
        'ld a, BATTLE_VARS_STATUS', 'call GetBattleVarAddr', 'bit FRZ, [hl]',
        'ret z', 'res FRZ, [hl]', 'call UpdateUserInParty',
        'ld hl, WasDefrostedText', 'jmp StdBattleTextbox']
    threshold = 1 + 20 * 255 // 100
    assert threshold == 52
    report = dict(source_repository='Rangi42/polishedcrystal', source_commit=source.PIN,
        source_variant='default (FAITHFUL undefined)', profile='B_POLISHED_MOVE_BALANCE',
        scope='Ordinary natural freeze checks in singles without either active battler using a gimmick.',
        rules=dict(random_range=256, thaw_below=threshold, thaw_numerator=52,
                   thaw_denominator=256, turn_cap=None,
                   self_thaw_moves=['SACRED_FIRE', 'SCALD', 'FLARE_BLITZ']),
        evidence=['The complete source frozen-action block checks the three self-thaw moves, then compares one BattleRandom byte against 1 + (20 percent).',
                  'The pinned percent macro uses integer multiplication by 255 and division by 100, giving a threshold of 52.',
                  'Failed rolls call CantMove and EndTurn; there is no duration counter or forced-thaw cap in the block.',
                  'DefrostUser clears freeze and updates the party status before displaying the thaw message.'],
        adapter='Use the exact byte threshold at the existing natural-freeze action gate and ignore the native freeze counter in the source scope. Do not add status-origin metadata or change saved identifiers. Existing self-thaw, item cure and native out-of-scope paths remain available.',
        gaps=['This ports the natural-thaw decision and probability, not the source RNG stream, animation or complete action-cancellation ordering.',
              'Self-thaw ordering against confusion, flinch, disobedience and other move blockers, incoming thaw attacks, freeze eligibility and optional ability/item combinations remain separate audits.',
              'Native-profile battles, doubles and either active gimmick retain native timer and chance rules. Optional freezing attacks in ordinary source-profile singles use the same natural status rule; their other effects are not certified.'])
    header = f'/* Generated by build_freeze.py from Polished Crystal {source.PIN}. */\n'
    header += '#define POLISHED_FREEZE_ROLL_RANGE 256\n'
    header += f'#define POLISHED_FREEZE_THAW_THRESHOLD {threshold}\n'
    return {source.ROOT/'include/constants/polished_freeze.h': header,
            source.ROOT/'tools/polished_port/manifests/freeze.json': json.dumps(report, indent=2)+'\n'}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, expected in build().items():
        if args.check:
            assert path.read_text() == expected, f'Regenerate {path}'
        else:
            path.write_text(expected)
    print('PASS: pinned freeze uses a 52/256 natural-thaw roll without a turn cap')
