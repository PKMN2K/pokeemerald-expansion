#!/usr/bin/env python3
"""Import fixed HP payloads while preserving the GBA runtime representation."""
import argparse
import json

import build_pokemon_learnsets as source


def build():
    files = source.sources()
    rows = {}
    for line in source.default_lines(files['data/moves/moves.asm']):
        if line.startswith(('move SONIC_BOOM,', 'move DRAGON_RAGE,')):
            values = [x.strip() for x in line[5:].split(',')]
            name, effect, power, type_, accuracy, pp, chance, category = values
            assert effect == 'EFFECT_STATIC_DAMAGE' and category == 'SPECIAL' and chance == '0'
            rows[name] = dict(power=int(power), type=type_, accuracy=int(accuracy), pp=int(pp))
    assert rows == {'SONIC_BOOM': dict(power=20, type='NORMAL', accuracy=90, pp=20),
                    'DRAGON_RAGE': dict(power=40, type='DRAGON', accuracy=100, pp=10)}
    script = files['data/moves/effects.asm'].split('\nStaticDamage:\n', 1)[1].split('\nDoPoison:', 1)[0]
    assert '\tconstantdamage\n\tresettypematchup\n\tmoveanim\n\tfailuretext\n\tapplydamage' in script
    assert '\tdamagecalc' not in script and '\tdamagevariation' not in script and '\tcritical' not in script
    commands = files['engine/battle/effect_commands.asm']
    constant = commands.split('BattleCommand_constantdamage:', 1)[1].split('\n.reversal\n', 1)[0]
    assert 'ld a, BATTLE_VARS_MOVE_POWER\n\tcall GetBattleVar\n\tld b, a' in constant
    assert 'ld hl, wCurDamage\n\tld [hli], a\n\tld [hl], b' in constant
    matchup = commands.split('BattleCommand_resettypematchup:', 1)[1].split('\nINCLUDE ', 1)[0]
    assert 'call BattleCheckTypeMatchup' in matchup and 'ld a, EFFECTIVE' in matchup and 'ld a, ATKFAIL_IMMUNE' in matchup
    for path in ('engine/pokemon/summary/green_page.asm', 'engine/pokemon/mon_menu.asm'):
        display = files[path].split('ld hl, Moves + MOVE_POWER', 1)[1].split('.place_accuracy', 1)[0]
        assert 'call GetCurMoveProperty' in display and 'cp 2' in display and 'call PrintNum' in display
    banner = f'/* Generated by build_fixed_damage.py from Polished Crystal {source.PIN}. */\n'
    header = banner + '#ifndef GUARD_CONSTANTS_POLISHED_FIXED_DAMAGE_H\n#define GUARD_CONSTANTS_POLISHED_FIXED_DAMAGE_H\n\n'
    header += ''.join(f'#define POLISHED_{name}_DAMAGE {row["power"]}\n' for name, row in rows.items())
    header += '\n#endif\n'
    manifest = dict(source_repository='Rangi42/polishedcrystal', source_commit=source.PIN,
        source_variant='default (FAITHFUL undefined)', moves=rows,
        adapter=dict(runtime_power=1, runtime_effect='EFFECT_FIXED_HP_DAMAGE',
                     payload='argument.fixedDamage', display='GetMoveDisplayPower returns the imported fixed HP payload'),
        scope='Fixed damage amount, type immunities, protection/substitute behavior, AI damage use and source numeric power display.',
        gaps=['Source accuracy RNG, general ability/item interaction timing, AI scoring and original move animations remain separate audits.',
              'Current GBA UI surfaces use source power values; original source layout/art is not imported by this suite.'])
    return {source.ROOT/'include/constants/polished_fixed_damage.h': header,
            source.ROOT/'tools/polished_port/manifests/fixed_damage.json': json.dumps(manifest, indent=2)+'\n'}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, expected in build().items():
        if args.check:
            assert path.read_text() == expected, f'Regenerate {path}'
        else:
            path.write_text(expected)
    print('PASS: pinned fixed damage 20/40, runtime adapter, immunity handling and source display contract')
