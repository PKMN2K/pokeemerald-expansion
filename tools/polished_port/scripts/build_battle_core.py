#!/usr/bin/env python3
"""Source contracts and numerical vectors for shared battle execution rules."""
import argparse
import itertools
import json
import re

import build_battle_suite as archive

ROOT = archive.ROOT


def confusion(level, attack, defense, astage, dstage):
    # TruncateHL_BC repeatedly shifts both input words, flooring each at one.
    while max(attack, defense) > 255:
        attack, defense = max(1, attack >> 1), max(1, defense >> 1)
    numerator = (level * 2 // 5 + 2) * 40 * attack
    def scale(stage):
        return (stage - 4, 2) if stage >= 6 else (2, 8 - stage)
    a, b = scale(astage)
    numerator = numerator * a // b
    a, b = scale(12 - dstage)
    numerator = numerator * a // b
    result = numerator // max(1, defense) // 50
    return 0xff00 if result >= 0xff00 else result + 2


def build():
    f = {p:r['text'] for p,r in archive.authenticated_sources().items()}
    effect = f['engine/battle/effect_commands.asm']
    truncate = effect.split('TruncateHL_BC:', 1)[1].split('ThickClubOrLightBallBoost:', 1)[0]
    assert 'call HalveBC' in truncate and 'srl h\n\trr l' in truncate and 'jr nz, .loop' in truncate
    assert 'inc l' in truncate
    confused = effect.split('ConfusedDamageCalc:', 1)[1].split('BattleCommand_damagecalc:', 1)[0]
    assert re.findall(r'call (\w+)', confused) == ['DamagePass1','DamagePass2','ApplyStatBoostDamage','ApplyDefStatBoostDamage','DamagePass3']
    assert 'jmp DamagePass4' in confused
    hit = effect.split('HitSelfInConfusion:', 1)[1].split('ApplyAttackBoosts:', 1)[0]
    assert 'call ResetDamage' in hit and 'call TruncateHL_BC\n\tld d, 40' in hit
    assert 'farcall SubtractHPFromUser_SkipItems' in effect.split('TakeOpponentDamage:',1)[1].split('TakeDamage:',1)[0]
    assert 'ld [hl], $ff' in effect.split('DamagePass4:',1)[1].split('BattleCommand_constantdamage:',1)[0]
    assert 'and $f' in f['home/math.asm'] and 'hMultiplicand:: ds 3' in f['ram/hram.asm']
    default = f['data/options/default_options.asm'].split('; wInitialOptions\n',1)[1].split('\n',2)[0]
    assert default.strip().startswith('db ') and 'AFFECTION_OPT' not in default
    speed = f['engine/battle/core.asm'].split('GetSpeed::',1)[1].split('CheckContestBattleOver:',1)[0]
    assert speed.index('call HasUserFainted') < speed.index('farcall FarDoStatChangeMod') < speed.index('cp QUICK_FEET') < speed.index('farcall ApplySpeedAbilities') < speed.index('cp HELD_QUICK_POWDER')
    assert 'lb bc, $ff, $ff' in speed and 'farcall UserValidBattleItem' in speed
    valid_item = effect.split('UserValidBattleItem:',1)[1].split('.ValidBattleItemTable',1)[0]
    assert 'wBattleMonSpecies - wBattleMonItem' in valid_item and 'transformed' not in valid_item
    start_weather = f['engine/battle/move_effects/weather.asm']
    assert 'cp b\n\tjmp z, BattleEffect_ButItFailed' in start_weather
    assert 'call GetItemBoostedDuration\n\tld [wWeatherCount], a' in start_weather
    assert 'ld a, 5' in effect.split('GetItemBoostedDuration:',1)[1].split('PrintDoesntAffect:',1)[0]
    weather = f['engine/battle/abilities.asm'].split('SnowWarningAbility:',1)[1].split('IntimidateAbility:',1)[0]
    assert 'ld a, WEATHER_HAIL' in weather and 'farcall BattleCommand_starthail' in weather
    hail = '\n'.join(archive.source.default_lines(f['engine/battle/endturn.asm'].split('\n.HandleHail\n',1)[1].split('WeatherEndedMessages:',1)[0]))
    assert 'cp SLUSH_RUSH\nret z' in hail
    critical = effect.split('BattleCommand_critical:',1)[1].split('SetCrit:',1)[0]
    assert 'cp 3\n\tjr nc, .guranteed_crit' in critical and 'ld a, 24\n\tcall BattleRandomRange' in critical
    high = re.findall(r'\bdb ([A-Z][A-Z_]+)', f['data/moves/critical_hit_moves.asm'])
    assert len(high) == 9
    assert [int(n) for n in re.findall(r'\bdb (\d+)', f['data/battle/critical_hit_chances.asm'])] == [1,3,12,24]
    ids = archive.source.move_identities(archive.source.sources())[1:]
    lines = ['/* Generated from pinned default Polished Crystal. 0 optional; 1 normal; 2 high-crit. */',
             'static const u8 sPolishedCriticalMoves[MOVES_COUNT] = {']
    lines += [f'    [{r["target_move"]}] = {1 + (r["source_move"] in high)},' for r in ids]
    lines += ['};', 'static const u8 sPolishedCriticalNumerators[] = {1, 3, 12};', '']
    pairs = [(1,1),(3,5),(7,11),(101,100),(255,256),(256,255),(511,512),(1,1023),(1023,1),(65535,65535),(65535,1),(1,65535)]
    vectors = [(lv,a,d,ast,dst,confusion(lv,a,d,ast,dst)) for lv,(a,d),ast,dst in itertools.product((1,50,100,255),pairs,range(13),range(13))]
    header = ['/* Source-derived confusion arithmetic vectors, generated by build_battle_core.py. */',
              'static const struct { u16 attack, defense, damage; u8 level, attackStage, defenseStage; } sPolishedConfusionVectors[] = {']
    header += [f'    {{{a}, {d}, {damage}, {lv}, {ast}, {dst}}},' for lv,a,d,ast,dst,damage in vectors]
    header += ['};', '']
    report = dict(source_commit=archive.source.PIN, source_variant='default release, FAITHFUL undefined',
        rules=dict(confusion_vectors=len(vectors), confusion_power=40, confusion_input_reduction='Repeated simultaneous halving to bytes, floor each shifted value at one',
                   confusion_stage_order='Attack then inverse Defense on the numerator, before Defense and 50 division; DamagePass4 adds two or clamps to 0xff00',
                   affection_default=False, quick_powder_checks_copied_species=True, speed_order=['fainted raw stat','stage','paralysis unless Quick Feet','ability','item','65535 cap'],
                   critical_high_moves=high, critical_numerators=[1,3,12,24], critical_denominator=24,
                   weather_abilities=['DRIZZLE','DROUGHT','SAND_STREAM','SNOW_WARNING'], snow_warning_weather='HAIL', slush_rush_hail_immunity=True),
        source_paths=['engine/battle/core.asm','engine/battle/effect_commands.asm','engine/battle/abilities.asm','engine/battle/endturn.asm','engine/battle/move_effects/weather.asm','home/math.asm','home/battle.asm','engine/math/math.asm','ram/hram.asm','data/options/default_options.asm','data/moves/critical_hit_moves.asm','data/battle/critical_hit_chances.asm'],
        limits=['This establishes the listed calculations and default rules, not whole damage/action/residual ordering.',
                'Confusion berry consumption and global faint ordering remain open; optional Ice Face/Disguise keep native self-damage paths.',
                'Optional affection setting/menu and its source thresholds, external Future Sight, optional critical-boost states and exact RNG stream remain open/native.',
                'AI choice parity, capture/rewards and remaining domains in battle_suite.json remain open.'])
    return {ROOT/'src/data/polished_critical_hits.h':'\n'.join(lines), ROOT/'test/battle/polished_confusion_vectors.h':'\n'.join(header), ROOT/'tools/polished_port/manifests/battle_core.json':json.dumps(report,indent=2)+'\n'}


if __name__ == '__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    for path,content in build().items():
        if args.check:
            assert path.read_text()==content, f'Regenerate {path}'
        else:
            path.write_text(content)
    print('PASS: source confusion, Speed, critical, affection and weather contracts; 8112 arithmetic vectors')
