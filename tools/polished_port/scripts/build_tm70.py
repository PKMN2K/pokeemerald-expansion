#!/usr/bin/env python3
"""Import the pinned TM70 identity, original icon and successful-lesson rules."""
import argparse
import base64
import hashlib
import json
import re
import tempfile
from pathlib import Path
from build_pokemon_learnsets import ROOT, PIN
from convert_player_walking import _read_png_2bit_grayscale, _write_indexed_4bit_png
from polished_route30 import palette


def sources():
    folder = ROOT / 'tools/polished_port/fixtures/tm70'
    manifest = json.loads((folder / 'sources.json').read_text())
    assert manifest['commit'] == PIN
    result = {}
    for entry in manifest['files']:
        data = base64.b64decode((folder / entry['fixture']).read_text())
        assert hashlib.sha1(b'blob ' + str(len(data)).encode() + b'\0' + data).hexdigest() == entry['git_blob_sha1']
        result[entry['path']] = data
    return result


def build():
    raw = sources()
    f = {p:b.decode() for p,b in raw.items() if p.endswith('.asm')}
    tms = re.findall(r'^\s*add_tm (\w+)', f['constants/tmhm_constants.asm'], re.M)
    hms = re.findall(r'^\s*add_hm (\w+)', f['constants/tmhm_constants.asm'], re.M)
    assert len(tms) == 75 and tms[69] == 'FLASH' and 'FLASH' not in hms
    desc = f['data/moves/descriptions.asm'].split('FlashDescription:', 1)[1].split('done', 1)[0]
    description = '\\n'.join(re.findall(r'(?:text|next) "(.*)"', desc))
    assert description == "A move that lowers\\nthe foe's accuracy."
    assert 'TMHMIcon:: INCBIN "gfx/items/tm_hm.2bpp.lz"' in f['gfx/items.asm']
    icon_palette = f['engine/gfx/color.asm'].split('LoadTMHMIconPalette:', 1)[1].split('LoadSpecialItemIconPalette:', 1)[0]
    assert 'Moves + MOVE_TYPE' in icon_palette and 'TMHMTypeIconPals' in icon_palette
    colors = [tuple(map(int,c)) for c in re.findall(r'RGB\s+(\d+),\s*(\d+),\s*(\d+)', raw['gfx/items/tm_hm_types.pal'].decode())][:2]
    assert colors == [(28,28,29), (24,24,23)]
    # Follow the actual Bag call chain, not the dormant PP-conservation comment:
    # AskTeachTMHM clears LEARNING_TM before returning; TeachTMHM never sets it.
    tm = f['engine/items/tmhm2.asm']
    ask = tm.split('AskTeachTMHM:', 1)[1].split('ChooseMonToLearnTMHM:', 1)[0]
    assert ask.rstrip().endswith('res LEARNING_TM_F, [hl]\n\tret')
    teach = tm.split('\nTeachTMHM:', 1)[1].split('_GetTMHMName::', 1)[0]
    assert 'LEARNING_TM' not in teach and 'HAPPINESS_LEARNMOVE' in teach
    assert teach.index('predef LearnMove') < teach.index('call IsHM') < teach.index('predef ChangeHappiness')
    pack = f['engine/items/pack.asm'].split('.UseItem:', 1)[1].split('.HandleKeyItemSubmenu:', 1)[0]
    assert pack.index('AskTeachTMHM') < pack.index('ChooseMonToLearnTMHM') < pack.index('farcall TeachTMHM')
    assert 'LEARNING_TM' not in pack
    learn = f['engine/pokemon/learn.asm']
    assert 'cp FORGETTING_MOVE | LEARNING_TM\n\tjr nz, .pp_ok' in learn
    assert '.pp_ok\n\tld [hl], b' in learn
    # Both native SetMonMoveSlot and the source ordinary Bag flow reset the
    # replaced slot to base PP, clearing its old PP Ups. Empty slots do likewise.
    changes = f['data/events/happiness_changes.asm']
    row = [int(n.strip()) for n in re.search(r'db\s+([^;\n]+); Learned a move', changes)[1].split(',')]
    constants = f['constants/pokemon_data_constants.asm']
    thresholds = [int(re.search(rf'DEF HAPPINESS_THRESHOLD_{n} EQU (\d+)', constants)[1]) for n in (1,2)]
    assert row == [1,1,0] and thresholds == [100,160]
    happy = f['engine/events/happiness_egg.asm']
    extra = happy.split('GetExtraHappiness:', 1)[1].split('StepHappiness::', 1)[0]
    assert 'cp SOOTHE_BELL' in extra and 'cp LUXURY_BALL' in extra and extra.count('inc b') == 2
    assert 'bit MON_IS_EGG_F, [hl]\n\tret nz' in happy
    result = {}
    with tempfile.TemporaryDirectory() as tmp:
        src, out = Path(tmp)/'src.png', Path(tmp)/'out.png'
        src.write_bytes(raw['gfx/items/tm_hm.png'])
        w,h,pixels = _read_png_2bit_grayscale(src)
        assert (w,h) == (24,24)
        _write_indexed_4bit_png(out, [[3-p for p in row] for row in pixels])
        result[ROOT/'graphics/items/icons/polished_flash_tm.png'] = out.read_bytes()
    result[ROOT/'graphics/items/icon_palettes/polished_flash_tm.pal'] = palette(colors)
    result[ROOT/'src/data/polished_tm70_item.h'] = ('''/* Generated by build_tm70.py; sparse ID preserves existing saves. */
    [ITEM_TM70] =
    {
        .name = ITEM_NAME("TM70"),
        .price = 0, // Source machines are owned flags, not sellable inventory.
        .description = COMPOUND_STRING("%s"),
        .importance = TRUE,
        .pocket = POCKET_TM_HM,
        .type = ITEM_USE_PARTY_MENU,
        .fieldUseFunc = ItemUseOutOfBattle_TMHM,
        .iconPic = gItemIcon_PolishedFlashTM,
        .iconPalette = gItemIconPalette_PolishedFlashTM,
    },
''' % description).encode()
    result[ROOT/'src/data/polished_tm70_rules.h'] = (f'''/* Generated from Polished Crystal {PIN}. */
#define POLISHED_TM70_FRIENDSHIP_LOW {thresholds[0]}
#define POLISHED_TM70_FRIENDSHIP_HIGH {thresholds[1]}
static const u8 sPolishedTM70Friendship[] = {{{', '.join(map(str,row))}}};
''').encode()
    report = dict(source_commit=PIN, source_variant='default release', source_item='TM70 FLASH',
        target_item='ITEM_TM70', target_id=651, legacy_item='ITEM_HM_FLASH', legacy_id=686,
        source_rgb555=colors, source_dimensions=[24,24], description=description,
        rules=['Reusable TM; normal move forgetting; source species/form teaching compatibility.',
               'Elder Li awards TM70; existing HM05 saves keep their item and field access.',
               'No item/save ID or bag-capacity changes; sparse machine index is distinct from display number and HM category.',
               'Successful lesson friendship: +1/+1/+0 below 100/below 160/otherwise, additive Soothe Bell and Luxury Ball +1 each, clamp at 255.',
               'Actual source Bag flow clears LEARNING_TM before LearnMove: empty and replacement slots receive base PP, old PP Ups reset. The conditional PP-conservation code is unreachable through this flow.'],
        gaps=['Other source TM/HM/tutor identities remain incomplete.',
              'Legacy HM05 retains native item presentation and lesson friendship; Flash itself can now be forgotten.',
              'Bag/menu layout, boot-up and learning text, sound and animation retain native presentation.',
              'TM ownership uses a reusable GBA bag item, rather than source bit flags; no sale/hold/toss and price zero are storage adapters.'])
    result[ROOT/'tools/polished_port/manifests/tm70.json'] = (json.dumps(report,indent=2)+'\n').encode()
    return result


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    for path,data in build().items():
        if a.check: assert path.exists() and path.read_bytes()==data, f'Regenerate {path}'
        else: path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(data)
    print('PASS: pinned TM70 identity, icon, palette, lesson friendship and actual Bag PP flow')


if __name__ == '__main__': main()
