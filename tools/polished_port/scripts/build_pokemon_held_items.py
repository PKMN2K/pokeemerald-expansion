#!/usr/bin/env python3
"""Import pinned wild held-item identities, byte thresholds and missing icons."""
import argparse
import base64
import hashlib
import json
import re
import tempfile
from pathlib import Path

import build_pokemon_base_data as base
import build_pokemon_learnsets as source
from convert_player_walking import _read_png_2bit_grayscale, _write_indexed_4bit_png
from polished_route30 import palette

ROOT = source.ROOT
FIXTURES = ROOT / "tools/polished_port/fixtures/held_items"
OUTPUT = ROOT / "src/data/polished_wild_held_items.h"
ITEMS = ROOT / "src/data/polished_held_item_definitions.h"
MANIFEST = ROOT / "tools/polished_port/manifests/pokemon_held_items.json"
ALIASES = {
    "NO_ITEM": "NONE", "BRIGHTPOWDER": "BRIGHT_POWDER", "MARANGABERRY": "MARANGA_BERRY",
    "NEVERMELTICE": "NEVER_MELT_ICE", "SILVERPOWDER": "SILVER_POWDER",
    "TINYMUSHROOM": "TINY_MUSHROOM", "TWISTEDSPOON": "TWISTED_SPOON",
    "PINK_BOW": "POLISHED_PINK_BOW", "SILVER_LEAF": "POLISHED_SILVER_LEAF",
    "GOLD_LEAF": "POLISHED_GOLD_LEAF",
}
NEW_ITEMS = {"PINK_BOW": (880, "pink_bow", "PolishedPinkBow"),
             "SILVER_LEAF": (881, "leaf", "PolishedSilverLeaf"),
             "GOLD_LEAF": (882, "leaf", "PolishedGoldLeaf")}


def sources():
    manifest = json.loads((FIXTURES / "sources.json").read_text())
    assert manifest["commit"] == source.PIN
    files = {}
    for entry in manifest["files"]:
        data = base64.b64decode((FIXTURES / entry["fixture"]).read_text())
        sha = hashlib.sha1(b"blob " + str(len(data)).encode() + b"\0" + data).hexdigest()
        assert sha == entry["git_blob_sha1"], entry["path"]
        files[entry["path"]] = data
    return files


def catalog(files):
    constants = files["constants/item_constants.asm"].decode().split("DEF NUM_ITEMS", 1)[0]
    assert "const_skip" not in constants
    ids = re.findall(r"^\s*const (\w+)", constants, re.M)
    assert ids[0] == "NO_ITEM" and len(ids) == 255
    attributes = files["data/items/attributes.asm"].decode().split("assert_table_length NUM_ITEMS", 1)[0]
    attributes = [[v.strip() for v in r.split(",")] for r in re.findall(r"^\s*item_attribute (.+)", attributes, re.M)]
    names = re.findall(r'\bli "([^"]+)"', "\n".join(source.default_lines(files["data/items/names.asm"].decode())))
    descriptions = files["data/items/descriptions.asm"].decode()
    pointers = re.findall(r"\bdw (\w+)", descriptions.split("assert_table_length NUM_ITEMS", 1)[0])
    assert len(ids) == len(names) == len(attributes) + 1 == len(pointers) + 1
    result = {}
    for i, item in enumerate(ids[1:], 1):
        body = descriptions.split(pointers[i - 1] + ":", 1)[1].split("\tdone", 1)[0]
        text = "\\n".join(re.findall(r'(?:text|next) "([^"]+)"', body))
        assert len(attributes[i - 1]) == 6 and text, item
        result[item] = dict(source_id=i, source_name=names[i], source_attributes=attributes[i - 1], source_description=text)
    return result


def plural_name(files, name):
    rules = "\n".join(source.default_lines(files["data/text/plural_table.asm"].decode()))
    for suffix, replacement in re.findall(r'plural "([^"]*)",\s*"([^"]*)"', rules):
        if name.endswith(suffix):
            return (name[:-len(suffix)] if suffix else name) + replacement
    raise AssertionError(("Missing source plural rule", name))


def thresholds(files):
    macro = files["macros/data.asm"]
    assert 'DEF percent EQUS "* $ff / 100"' in macro
    core = "\n".join(source.default_lines(files["engine/battle/core.asm"].split("; Let's get the item:", 1)[1].split(".UpdateItem:", 1)[0]))
    boosted, ordinary = core.split(".compound_eyes:", 1)[1].split(".no_compound_eyes_or_amulet_coin:", 1)
    boost = [int(x) * 255 // 100 for x in re.findall(r"cp (\d+) percent", boosted)]
    normal = [int(x) * 255 // 100 for x in re.findall(r"cp (\d+) percent", ordinary)]
    assert boost == [153, 127] and normal == [127, 25]
    return dict(common=normal[0], rare=normal[1], boost_common=boost[0], boost_rare=boost[1])


def build():
    files = sources()
    items = catalog(files)
    rules = thresholds(source.sources())
    base_rows = json.loads(base.build()[base.MANIFEST])["records"]
    available = set(re.findall(r"\bITEM_\w+", (ROOT / "include/constants/items.h").read_text()))
    tokens = sorted({x for r in base_rows for x in r["source_held_items"]} - {"ALWAYS_ITEM_2"})
    mapped = {x: "ITEM_" + ALIASES.get(x, x) for x in tokens}
    assert set(mapped.values()) <= available
    assert len(mapped) == len(set(mapped.values())) == 71
    rows, unique = [], {}
    lines = ["/* Generated by build_pokemon_held_items.py; pinned default Polished Crystal. */"]
    lines += [f"#define POLISHED_HELD_{key.upper()} {value}" for key, value in rules.items()]
    lines.append("")
    for row in base_rows:
        common, rare = row["source_held_items"]
        assert rare != "ALWAYS_ITEM_2"
        always = common == "ALWAYS_ITEM_2"
        pair = ("ITEM_NONE" if always else mapped[common], mapped[rare], always)
        if pair not in unique:
            unique[pair] = "sPolishedHeld_" + row["target_species"].removeprefix("SPECIES_")
            lines.append(f'static const struct PolishedWildHeldItems {unique[pair]} = {{{pair[0]}, {pair[1]}, {"TRUE" if always else "FALSE"}}};')
        rows.append({k: row[k] for k in ("source_species", "source_form", "target_species", "source_file", "source_held_items")} |
                    dict(common=pair[0], rare=pair[1], always_rare=always))
    lines += ["", "static const struct PolishedWildHeldItems *const sPolishedWildHeldItems[NUM_SPECIES] = {"]
    lines += [f'    [{r["target_species"]}] = &{unique[r["common"], r["rare"], r["always_rare"]]},' for r in rows]
    lines += ["};", ""]
    result = {OUTPUT: "\n".join(lines).encode()}
    definitions = ["/* Generated source identities; existing native item IDs are unchanged. */"]
    icon_pointers = re.findall(r"\bdba (\w+)", files["data/items/icon_pointers.asm"].decode().split("assert_table_length NUM_ITEMS", 1)[0])
    pals = files["gfx/items/items.pal"].decode()
    assert pals.startswith("if !DEF(MONOCHROME)\n")
    colors = [tuple(map(int, m)) for m in re.findall(r"RGB\s+(\d+),\s*(\d+),\s*(\d+)", pals.split("else", 1)[0])]
    assert len(colors) == len(icon_pointers) * 2 == 510
    new_metadata = []
    with tempfile.TemporaryDirectory() as tmp:
        src, out = Path(tmp) / "src.png", Path(tmp) / "out.png"
        for token, (target_id, graphic, symbol) in NEW_ITEMS.items():
            data = items[token]
            data["source_plural_name"] = plural_name(files, data["source_name"])
            index = data["source_id"]
            icon = icon_pointers[index]
            # Consecutive SilverLeafIcon/GoldLeafIcon labels deliberately alias.
            blob = files["gfx/items.asm"].decode().split(icon + "::", 1)[1].split("INCBIN ", 1)[1].splitlines()[0]
            assert blob == f'"gfx/items/{graphic}.2bpp.lz"'
            src.write_bytes(files[f"gfx/items/{graphic}.png"])
            w, h, pixels = _read_png_2bit_grayscale(src)
            assert (w, h) == (24, 24)
            _write_indexed_4bit_png(out, [[3 - p for p in row] for row in pixels])
            stem = "polished_" + token.lower()
            result[ROOT / f"graphics/items/icons/{stem}.png"] = out.read_bytes()
            result[ROOT / f"graphics/items/icon_palettes/{stem}.pal"] = palette(colors[index * 2:index * 2 + 2])
            price, effect, param, pocket, field, battle = data["source_attributes"]
            assert (pocket, field, battle) == ("ITEM", "ITEMMENU_NOUSE", "ITEMMENU_NOUSE")
            assert (effect, param) == (("HELD_TYPE_BOOST", "FAIRY") if token == "PINK_BOW" else ("0", "0"))
            definitions += [f'    [{mapped[token]}] =', '    {', f'        .name = ITEM_NAME("{data["source_name"]}"),',
                            f'        .pluralName = ITEM_PLURAL_NAME("{data["source_plural_name"]}"),',
                            f'        .price = {price},', f'        .description = COMPOUND_STRING("{data["source_description"]}"),',
                            '        .pocket = POCKET_ITEMS,', '        .type = ITEM_USE_BAG_MENU,',
                            '        .fieldUseFunc = ItemUseOutOfBattle_CannotUse,',
                            f'        .iconPic = gItemIcon_{symbol},', f'        .iconPalette = gItemIconPalette_{symbol},']
            if token == "PINK_BOW":
                definitions += ['        .holdEffect = HOLD_EFFECT_TYPE_POWER,', '        .holdEffectParam = 20,',
                                '        .secondaryId = TYPE_FAIRY,', '        .sortType = ITEM_TYPE_TYPE_BOOST_HELD_ITEM,']
            definitions += ['    },']
            new_metadata.append(dict(source_item=token, target_item=mapped[token], target_id=target_id,
                                     source_icon=f"gfx/items/{graphic}.png", source_rgb555=colors[index * 2:index * 2 + 2], **data))
    result[ITEMS] = ("\n".join(definitions) + "\n").encode()
    manifest = dict(source_commit=source.PIN, source_variant="default; FAITHFUL and MONOCHROME undefined",
                    mapped_target_count=len(rows), byte_thresholds=rules,
                    semantics=["ALWAYS_ITEM_2 precedes legendary encounter override; legendary selects common without rolls.",
                               "Two independent 0..255 rolls; second only after first fails, including empty and equal-item rows.",
                               "Physical lead Compound Eyes/Super Luck (unless Egg/empty) or Amulet Coin; fainting does not disable boosts.",
                               "Mapped source rows override native and Altering Cave tables; explicit nonzero scripted items are preserved.",
                               "Unmapped species and disabled source profile retain native behavior; legendary fallback stays itemless."],
                    item_mapping=[dict(source_item=x, target_item=mapped[x], **(items[x] if x != "NO_ITEM" else dict(source_id=0))) for x in tokens],
                    new_items=new_metadata, records=rows,
                    remaining_gaps=["Existing mapped item prices/descriptions/art/effects still use native definitions until individually ported.",
                                    "Pink Bow uses the native 20% Fairy-type damage adapter; full source damage order/rounding remains pending.",
                                    "Leaf tutor placements, full item catalog, source TM inventory/numbering and broader item mechanics remain pending.",
                                    "GBA RNG supplies uniform bytes; this ports source branch probabilities, not the GBC RNG sequence."])
    result[MANIFEST] = (json.dumps(manifest, indent=2) + "\n").encode()
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, data in build().items():
        if args.check:
            assert path.is_file() and path.read_bytes() == data, f"Regenerate {path.relative_to(ROOT)}"
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    print("PASS: pinned held-item data, thresholds, definitions and original icons" if args.check else "Wrote pinned held-item import")


if __name__ == "__main__":
    main()
