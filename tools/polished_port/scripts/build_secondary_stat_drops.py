#!/usr/bin/env python3
"""Import target stat-drop secondary data from the pinned default source."""
import argparse
import json
import re

import build_pokemon_learnsets as source

EFFECTS = {
    'EFFECT_ATTACK_DOWN_HIT': ('AttackDownHit', 'ATTACK', 'STAT_ATK', 'attack'),
    'EFFECT_DEFENSE_DOWN_HIT': ('DefenseDownHit', 'DEFENSE', 'STAT_DEF', 'defense'),
    'EFFECT_SPEED_DOWN_HIT': ('SpeedDownHit', 'SPEED', 'STAT_SPEED', 'speed'),
    'EFFECT_SP_ATK_DOWN_HIT': ('SpecialAttackDownHit', 'SP_ATTACK', 'STAT_SPATK', 'spAtk'),
    'EFFECT_SP_DEF_DOWN_HIT': ('SpecialDefenseDownHit', 'SP_DEFENSE', 'STAT_SPDEF', 'spDef'),
    'EFFECT_ACCURACY_DOWN_HIT': ('AccuracyDownHit', 'ACCURACY', 'STAT_ACC', 'accuracy'),
}


def records():
    files = source.sources()
    rows = [[v.strip() for v in line[5:].split(',')] for line in
            source.default_lines(files['data/moves/moves.asm'].split('Moves::', 1)[1])
            if line.startswith('move ')]
    identities = source.move_identities(files)[1:]
    assert len(rows) == len(identities) == 255
    for effect, (label, stat, _, _) in EFFECTS.items():
        script = files['data/moves/effects.asm'].split('\n'+label+':', 1)[1].split('\n\tendmove', 1)[0]
        assert script.index('\tapplydamage') < script.index('\teffectchance') < script.index('\tloweroppstathit '+stat)
        assert re.search(r'^\tloweroppstathit '+stat+r'$', script, re.M)
    commands = files['engine/battle/effect_commands.asm']
    assert '_LowerOppStatHit:\n\tor STAT_TARGET | STAT_LOWER | STAT_CANMISS | STAT_SECONDARY | STAT_SILENT' in commands
    # Bare source stat IDs have a zero amount nibble, decoded as one stage.
    constants = files['constants/battle_constants.asm']
    assert '\tconst_def\n\tconst ATTACK\n\tconst DEFENSE\n\tconst SPEED\n\tconst SP_ATTACK\n\tconst SP_DEFENSE\n\tconst ACCURACY' in constants
    assert '; Perform the stat change\n\tld a, [wChangedStat]\n\tand $f0\n\tswap a\n\tinc a\n\tld c, a' in files['engine/battle/stats.asm']
    chance = commands.split('\nBattleCommand_effectchance:', 1)[1].split('\nBattleCommand_lowersub:', 1)[0]
    assert 'call HasOpponentFainted\n\tjr z, EffectChanceFailed' in chance
    assert 'call CheckSubHit\n\tjr nz, EffectChanceFailed' in chance
    assert 'cp SHIELD_DUST\n\tjr z, EffectChanceFailed' in chance
    assert 'cp HELD_COVERT_CLOAK\n\tjr z, EffectChanceFailed' in chance
    assert 'cp SHEER_FORCE\n\tjr z, EffectChanceFailed' in chance
    assert 'cp SERENE_GRACE\n\tjr nz, .skip_serene_grace\n\tsla b' in chance
    assert 'ld a, 100\n\tcall BattleRandomRange\n\tcp b\n\tjr c, EffectChanceEnd' in chance
    result = []
    for identity, row in zip(identities, rows, strict=True):
        move, effect, power, type_, accuracy, pp, chance, category = row
        assert move == identity['source_move']
        if effect not in EFFECTS:
            continue
        label, stat, target_stat, field = EFFECTS[effect]
        assert category != 'STATUS' and 0 < int(chance) <= 100
        result.append(dict(**identity, source_effect=effect, source_stat=stat,
            target_stat=target_stat, target_field=field, stages=1, chance=int(chance)))
    assert len(result) == 18 and next(r for r in result if r['source_move']=='OCTAZOOKA')['chance']==30
    return result


def build():
    rows = records()
    header = f'/* Generated by build_secondary_stat_drops.py from Polished Crystal {source.PIN}. */\n'
    header += '#ifndef GUARD_CONSTANTS_POLISHED_SECONDARY_STAT_DROPS_H\n#define GUARD_CONSTANTS_POLISHED_SECONDARY_STAT_DROPS_H\n\n'
    header += '#define POLISHED_SECONDARY_STAT_DROP_STAGES 1\n'
    header += ''.join(f'#define POLISHED_{r["source_move"]}_SECONDARY_CHANCE {r["chance"]}\n' for r in rows)
    header += '\n#endif\n'
    report = dict(source_repository='Rangi42/polishedcrystal', source_commit=source.PIN,
        source_variant='default (FAITHFUL undefined)', profile='B_POLISHED_MOVE_BALANCE',
        moves=rows, selection='Compile-time POLISHED_BALANCE adapters; stable target move IDs.',
        scope='Secondary chance, target stat and one-stage amount for all 18 source damaging target stat-drop moves; focused ordinary-singles gate regressions.',
        source_probability='BattleRandomRange(100) < chance; Serene Grace doubles the chance; Sheer Force suppresses it.',
        gaps=['Other secondary families, primary/status effects, source flags/priority and complete damage/accuracy/AI remain separate audits.',
              'The engine random stream, global RNG call ordering and full source ability/item/stat-change semantics are not imported by these data adapters.',
              'Original battle animations and source UI artwork/layout remain open. Expansion-only formats, abilities and gimmicks retain their native framework.'])
    return {source.ROOT/'include/constants/polished_secondary_stat_drops.h': header,
            source.ROOT/'tools/polished_port/manifests/secondary_stat_drops.json': json.dumps(report, indent=2)+'\n'}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, expected in build().items():
        if args.check:
            assert path.read_text() == expected, f'Regenerate {path}'
        else:
            path.write_text(expected)
    print('PASS: 18 pinned target stat-drop secondary chances, stats and one-stage amounts')
