#!/usr/bin/env python3
"""Import default-source Metronome draws/exclusions and Struggle recoil rules."""
import argparse
import json
import re

import build_pokemon_learnsets as source


def build():
    files = source.sources()
    identities = source.move_identities(files)
    assert len(identities) == 256 and identities[-1]['source_move'] == 'STRUGGLE'
    excluded = re.findall(r'^\s*db (\w+)', files['data/moves/metronome_exception_moves.asm'], re.M)
    assert excluded == ['NO_MOVE', 'COUNTER', 'DESTINY_BOND', 'ENDURE', 'METRONOME',
                        'MIRROR_COAT', 'PROTECT', 'SKETCH', 'SLEEP_TALK', 'THIEF', 'TRANSFORM', 'STRUGGLE']
    command = files['engine/battle/move_effects/metronome.asm']
    assert '.GetMove:\n\tcall BattleRandom' in command
    assert 'call IsInByteArray\n\tpop bc\n\tjr c, .GetMove' in command
    assert 'call CheckUserMove\n\tjr z, .GetMove' in command
    assert 'call UpdateMoveData\n\tjmp ResetTurn' in command
    commands = files['engine/battle/effect_commands.asm']
    known = commands.split('\nCheckUserMove:', 1)[1].split('\nBoostJumptable:', 1)[0]
    assert 'ld de, wBattleMonMoves' in known and 'ld de, wEnemyMonMoves' in known
    assert 'ld c, NUM_MOVES' in known and 'cp b\n\tret z' in known
    assert 'PP' not in known  # Every current move slot excludes the move, even at zero PP.
    recoil = commands.split('\nBattleCommand_recoil:', 1)[1].split('\nBattleCommand_confusetarget:', 1)[0]
    assert recoil.index('jr z, .StruggleRecoil') < recoil.index('cp ROCK_HEAD') < recoil.index('cp MAGIC_GUARD')
    assert '.StruggleRecoil\n\tcall GetQuarterMaxHP\n\tjr .recoil_floor' in recoil
    assert '.recoil_floor\n\tcall FloorBC\n\tpredef SubtractHPFromUser' in recoil
    hp = files['home/battle.asm'].split('GetQuarterMaxHP::', 1)[1].split('GetMaxHP::', 1)[0]
    assert 'call GetHalfMaxHP\n\tjr HalveBC' in hp
    assert 'HalveBC::\n\tsrl b\n\trr c' in hp
    assert 'FloorBC::\n\tld a, c\n\tor b\n\tret nz\n\tinc c' in hp
    rows = [dict(**r, excluded=r['source_constant'] in excluded) for r in identities]
    assert sum(not r['excluded'] for r in rows) == 244
    banner = f'/* Generated by build_metronome_struggle.py from Polished Crystal {source.PIN}. */\n'
    header = banner + '#ifndef GUARD_CONSTANTS_POLISHED_METRONOME_STRUGGLE_H\n#define GUARD_CONSTANTS_POLISHED_METRONOME_STRUGGLE_H\n\n'
    header += '#define POLISHED_METRONOME_ROLL_COUNT 256\n#define POLISHED_METRONOME_POOL_SIZE 244\n'
    header += '#define POLISHED_STRUGGLE_RECOIL_DIVISOR 4\n#define POLISHED_STRUGGLE_RECOIL_MINIMUM 1\n\n'
    header += '// Source draw IDs, not target move IDs; aliases resolve through the default table.\n'
    header += ''.join(f'#define POLISHED_METRONOME_ROLL_{r["source_move"]} {r["source_id"]}\n' for r in rows)
    header += '\n#endif\n'
    table = banner + 'static const enum Move sPolishedMetronomeMoves[POLISHED_METRONOME_ROLL_COUNT] = {\n'
    table += ''.join(f'    [{r["source_id"]}] = {"MOVE_NONE" if r["excluded"] else r["target_move"]}, // {r["source_move"]}\n' for r in rows)
    table += '};\n'
    manifest = dict(source_repository='Rangi42/polishedcrystal', source_commit=source.PIN,
        source_variant='default (FAITHFUL undefined)', profile='B_POLISHED_MOVE_BALANCE',
        metronome=dict(draw_range=[0, 255], rejection_sampling=True, excludes_current_moves=True,
            checks_all_four_slots=True, ignores_known_move_pp=True, excludes_native_bans=False,
            base_pool_size=244, excluded_source_constants=excluded, rolls=rows),
        struggle=dict(recoil='max(1, floor(maximum HP / 4))', divisor=4, minimum=1,
            bypasses_rock_head_and_magic_guard=True),
        scope='Metronome source candidate identities, rejection predicates and conditional uniform probabilities; Struggle recoil amount and focused ordinary singles gates.',
        gaps=['The random generator remains the GBA engine PRNG: this preserves the byte-domain rejection distribution, not the source hardware/link random stream or global RNG call timing.',
              'The selected moves retain their individual documented effect/flag/probability gaps; importing the pool does not certify every called effect.',
              'Move-calling bookkeeping, PP-exhaustion selection, general damage and AI rules, source UI and animations remain separate audits.',
              'Expansion-only battle formats, abilities and gimmicks retain their native framework.'])
    return {source.ROOT/'include/constants/polished_metronome_struggle.h': header,
            source.ROOT/'src/data/polished_metronome_moves.h': table,
            source.ROOT/'tools/polished_port/manifests/metronome_struggle.json': json.dumps(manifest, indent=2)+'\n'}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, expected in build().items():
        if args.check:
            assert path.read_text() == expected, f'Regenerate {path}'
        else:
            path.write_text(expected)
    print('PASS: 256 pinned Metronome draws, 12 exclusions, 244 candidates and floor-quarter Struggle recoil')
