#!/usr/bin/env python3
"""Import Return's power constants and check its pinned damage-command order."""
import argparse
import re

import build_pokemon_learnsets as source

OUTPUT = source.ROOT / "include/constants/polished_return_power.h"


def build():
    files = source.sources()
    constants = files["constants/pokemon_data_constants.asm"]
    threshold = int(re.search(r"DEF MAX_RETURN_HAPPINESS\s+EQU (\d+)", constants)[1])
    power = files["engine/battle/move_effects/return.asm"]
    maximum = int(re.search(r"ld a, (\d+)\n\tldh \[hMultiplier\], a", power)[1])
    assert "ld hl, wBattleMonHappiness" in power and "ld hl, wEnemyMonHappiness" in power
    assert "farcall Multiply\n\tld a, MAX_RETURN_HAPPINESS\n\tldh [hDivisor], a\n\tld b, 4\n\tfarcall Divide\n\tldh a, [hQuotient + 2]" in power
    assert f"cp {maximum}\n\tjr c, .got_bp\n\tld a, {maximum}\n.got_bp\n\tld d, a" in power
    assert (maximum, threshold) == (102, 160)
    moves = files["data/moves/moves.asm"]
    assert re.search(r"move RETURN,\s+EFFECT_RETURN,\s+1, NORMAL,\s+100, 20,\s+0, PHYSICAL", moves)
    assert "FRUSTRATION" not in moves

    # Zero raw power skips the main formula, but the subsequent stab command
    # clamps a non-immune hit to one. It is not vanilla Gen2's zero-damage rule.
    script = files["data/moves/effects.asm"].split("\nReturn:\n", 1)[1].split("\nSacredFire:", 1)[0]
    assert "damagestats\n\thappinesspower\n\tdamagecalc\n\tstab\n\tdamagevariation\n\tmoveanim" in script
    engine = files["engine/battle/effect_commands.asm"]
    calc = engine.split("BattleCommand_damagecalc:", 1)[1].split("\n.skip_zero_damage_check\n", 1)[0]
    assert "ld a, d\n\tand a\n\tret z" in calc
    stab = engine.split("BattleCommand_stab:", 1)[1].split("CheckAirborneAfterMoldBreaker:", 1)[0]
    assert "; damage ended up 0, so set it to 1\n\tinc a\n\tld [hl], a" in stab
    assert "ld a, ATKFAIL_IMMUNE" in stab
    variation = engine.split("BattleCommand_damagevariation:", 1)[1].split("BattleCommand_checkhit:", 1)[0]
    assert "ld a, [hl]\n\tcp 2\n\tret c" in variation

    return (f"/* Generated by build_return_power.py from Polished Crystal {source.PIN}. */\n"
            "#ifndef GUARD_CONSTANTS_POLISHED_RETURN_POWER_H\n"
            "#define GUARD_CONSTANTS_POLISHED_RETURN_POWER_H\n\n"
            f"#define POLISHED_RETURN_MAX_POWER {maximum}\n"
            f"#define POLISHED_RETURN_MAX_HAPPINESS {threshold}\n"
            f"#define POLISHED_RETURN_MIN_HAPPINESS {(threshold + maximum - 1) // maximum}\n\n"
            "#endif\n").encode()


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = build()
    if args.check:
        assert OUTPUT.read_bytes() == data, "Regenerate source Return power"
    else:
        OUTPUT.write_bytes(data)
    print("PASS: source Return 102/160 scaling, cap, command order and post-modifier damage floor")
