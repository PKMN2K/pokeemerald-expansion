#!/usr/bin/env python3
"""Authenticate the pinned escape routines and emit independent byte-ALU vectors."""
import argparse
import hashlib
import json

import build_battle_suite as source

ROOT = source.ROOT
MANIFEST = ROOT/'tools/polished_port/manifests/escape.json'
VECTORS = ROOT/'test/battle/polished_escape_vectors.h'


def threshold(player, enemy, previous):
    """Interpret CheckRunSpeed's word shifts, byte divisor, carry and CP."""
    attempts = (previous + 1) & 255
    if player >= enemy:
        return 256
    dividend = player
    for _ in range(5):
        dividend = (dividend + dividend) & 65535
    divisor = (enemy >> 2) & 255
    if not divisor:
        return 256
    quotient = dividend // divisor
    if quotient >> 8:
        return 256
    while True:
        attempts = (attempts - 1) & 255
        if not attempts:
            return quotient + 1  # CP random; equality succeeds.
        quotient += 30
        if quotient > 255:
            return 256


def build():
    files = source.authenticated_sources()
    core = files['engine/battle/core.asm']['text']
    run = core.split('CheckRunSpeed:', 1)[1].split('GetMonBackpic:', 1)[0]
    assert 'rept 5 ; multiply player speed by 32' in run
    assert 'ld a, e\n\tand a ; prevent division by 0' in run
    assert 'ld hl, wNumFleeAttempts\n\tinc [hl]' in run
    assert 'cp b\n\tjr nc, .can_escape' in run
    assert 'BattleMenu_Fight:' in core and 'ld [wNumFleeAttempts], a' in core.split('BattleMenu_Fight:', 1)[1].split('BattleMenu_Bait:', 1)[0]
    assert run.index('cp RUN_AWAY') < run.index('cp HELD_ESCAPE') < run.index('call CheckIfUserIsGhostType')
    enemy = core.split('EnemyCanFlee:', 1)[1].split('CompareMovePriority:', 1)[0]
    assert 'and 1 << FRZ | SLP_MASK' in enemy and 'HELD_ESCAPE' not in enemy
    speed = core.split('GetSpeed::', 1)[1].split('CheckContestBattleOver:', 1)[0]
    assert all(x in speed for x in ('HELD_QUICK_POWDER', 'HELD_IRON_BALL', 'HELD_CHOICE'))
    assert all(x not in speed for x in ('HELD_MACHO_BRACE', 'HELD_EV_DOUBLE', 'HELD_POWER_ITEM'))
    persistence = core.split('BattleEnd_HandleRoamMons:', 1)[1].split('GetRoamMonHP:', 1)[0]
    assert 'res TOX, a' in persistence
    speeds = [0, 1, 2, 3, 4, 5, 31, 32, 63, 64, 99, 100, 127, 255, 256,
              511, 1023, 1024, 1025, 2047, 2048, 2049, 4095, 65535]
    vectors = [(p, e, a, threshold(p, e, a)) for p in speeds for e in speeds
               for a in (0, 1, 2, 3, 7, 8, 9, 254, 255)]
    text = ['/* Generated by build_escape.py from authenticated CheckRunSpeed semantics. */',
            'static const u16 sPolishedEscapeVectors[][4] = {']
    text += ['    {' + ', '.join(map(str, row)) + '},' for row in vectors]
    text += ['};', '']
    manifest = dict(source_commit=source.source.PIN, source_variant='default; FAITHFUL undefined',
        source_anchors={'engine/battle/core.asm': files['engine/battle/core.asm']['sha']},
        vectors=len(vectors), vector_sha256=hashlib.sha256(json.dumps(vectors).encode()).hexdigest(),
        contracts=['Use effective Speed without Quick Claw; training EV items do not reduce source Speed.',
                   'Increment the byte attempt counter before comparing Speed; only prior attempts add 30.',
                   'Choosing Fight resets flee attempts; switching and items preserve the counter.',
                   'Shift the player word five times, divide by the low byte of enemy Speed / 4, and saturate on carry.',
                   'Escape succeeds on equality with the random byte; zero divisor and high quotient guarantee escape.',
                   'Run Away precedes escape items and Ghost typing; move traps precede trapping abilities.',
                   'A roaming enemy checks traps and sleep/freeze both when choosing and executing its flee action.',
                   'A roamer locked into charging, recharge, Rampage or Rollout does not select a flee action or grant a free player escape.',
                   'Enemy escape ignores Smoke Ball; a source roamer retains ordinary poison after toxic poison.'],
        complete_behavior_parity=False,
        remaining=['Source special battle-type bindings, trainer forfeiture, replacement-menu escape and full Safari/controller flow remain open.',
                   'Roamer creation, source map routes, full save/encounter lifecycle and outcome sequencing remain open; native HP capacity is preserved.',
                   'Exact random-stream call order and source text/animation timing remain unverified.'])
    return {VECTORS: '\n'.join(text), MANIFEST: json.dumps(manifest, indent=2)+'\n'}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in build().items():
        if args.check:
            assert path.read_text() == content, f'Regenerate {path}'
        else:
            path.write_text(content)
    print('PASS: authenticated escape contracts and 5184 byte-ALU vectors')
