#!/usr/bin/env python3
"""Import default-source Hidden Power data and its six-DV type selection."""
import argparse
import json
import re

import build_pokemon_learnsets as source


def build():
    files = source.sources()
    routine = '\n'.join(source.default_lines(files['engine/battle/hidden_power.asm']))
    assert 'ld bc, 3\nld de, 1' in routine
    assert 'swap a\nand %00010001\nsrl a' in routine
    assert 'sla e\nand a\ncall nz, .add_bit\nsla e' in routine
    assert 'cp 63\nld e, 17\njr z, .got_type\nsrl a\nsrl a\ninc a\nld e, a' in routine
    constants = files['constants/pokemon_data_constants.asm']
    assert 'DEF MON_HP_ATK_DV' in constants and 'DEF MON_DEF_SPE_DV' in constants and 'DEF MON_SAT_SDF_DV' in constants
    types = re.findall(r'^\s*const (\w+)', files['constants/type_constants.asm'].split('DEF NUM_TYPES', 1)[0], re.M)
    assert types == ['NORMAL', 'FIGHTING', 'FLYING', 'POISON', 'GROUND', 'ROCK', 'BUG', 'GHOST', 'STEEL', 'FIRE', 'WATER', 'GRASS', 'ELECTRIC', 'PSYCHIC', 'ICE', 'DRAGON', 'DARK', 'FAIRY', 'UNKNOWN_T']
    row = next(line for line in source.default_lines(files['data/moves/moves.asm']) if line.startswith('move HIDDEN_POWER,'))
    assert [x.strip() for x in row[5:].split(',')] == ['HIDDEN_POWER', 'EFFECT_HIDDEN_POWER', '70', 'UNKNOWN_T', '100', '15', '0', 'SPECIAL']
    script = files['data/moves/effects.asm'].split('\nHiddenPower:\n', 1)[1].split('\nRainDance:', 1)[0]
    assert 'hiddenpower\n\tdamagestats\n\tdamagecalc\n\tstab' in script
    assert 'ld a, [wAttackMissed]\n\tand a\n\tret nz\n\tfarjp SetHiddenPowerType' in files['engine/battle/move_effects/hidden_power.asm']
    anticipation = files['engine/battle/abilities.asm'].split('AnticipationAbility:', 1)[1].split('\nFriskAbility:', 1)[0]
    assert 'call GetFixedMoveStruct' in anticipation and 'farcall BattleCheckTypeMatchup' in anticipation
    assert 'SetHiddenPowerType' not in anticipation
    selected = [types[17 if bits == 63 else (bits >> 2) + 1] for bits in range(64)]
    banner = f'/* Generated by build_hidden_power.py from Polished Crystal {source.PIN}. */\n'
    header = banner + '''#ifndef GUARD_CONSTANTS_POLISHED_HIDDEN_POWER_H
#define GUARD_CONSTANTS_POLISHED_HIDDEN_POWER_H

#define POLISHED_HIDDEN_POWER_POWER 70
#define POLISHED_HIDDEN_POWER_TYPE TYPE_MYSTERY
// The port stores source DV d as IV 2*d; either member of that IV pair
// projects to the same source DV without changing saved IVs or their width.
#define POLISHED_HIDDEN_POWER_IV_SHIFT 1

#endif
'''
    table = banner + 'static const u8 sPolishedHiddenPowerTypes[64] =\n{\n'
    table += ''.join('    ' + ', '.join('TYPE_' + t for t in selected[i:i+4]) + ',\n' for i in range(0, 64, 4))
    table += '};\n'
    manifest = dict(source_repository='Rangi42/polishedcrystal', source_commit=source.PIN,
        source_variant='default (FAITHFUL undefined)', power=70, table_type='UNKNOWN_T', target_table_type='TYPE_MYSTERY',
        dv_order=['HP', 'Attack', 'Defense', 'Speed', 'SpAttack', 'SpDefense'],
        iv_adapter='DV = IV >> 1; preserve all stored 0..31 IVs and the existing trainer DV*2 conversion',
        type_by_dv_parity=selected,
        scope='Fixed base power, static unknown type, and dynamic six-DV typing including Fairy in the shared battle/AI/optional-display accessor.',
        gaps=['Original move animation and source UI/guru presentation are not imported here.',
              'General damage rounding, accuracy RNG, ability effects, DV/stat generation and trainer construction retain their separate audits.'])
    return {source.ROOT/'include/constants/polished_hidden_power.h': header,
            source.ROOT/'src/data/polished_hidden_power_types.h': table,
            source.ROOT/'tools/polished_port/manifests/hidden_power.json': json.dumps(manifest, indent=2)+'\n'}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, expected in build().items():
        if args.check:
            assert path.read_text() == expected, f'Regenerate {path}'
        else:
            path.write_text(expected)
    print('PASS: pinned Hidden Power 70 power, unknown table type and all 64 default-source DV type patterns')
