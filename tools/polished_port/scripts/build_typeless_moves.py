#!/usr/bin/env python3
"""Import the pinned default Metronome/Struggle UNKNOWN_T table entries."""
import argparse
import json

import build_pokemon_learnsets as source


def build():
    files = source.sources()
    rows = {}
    for line in source.default_lines(files['data/moves/moves.asm']):
        if line.startswith(('move METRONOME,', 'move STRUGGLE,')):
            name, effect, power, type_, accuracy, pp, chance, category = [v.strip() for v in line[5:].split(',')]
            assert type_ == 'UNKNOWN_T' and accuracy == '-1' and chance == '0'
            rows[name] = dict(effect=effect, power=int(power), source_type=type_,
                              target_type='TYPE_MYSTERY', accuracy=-1, pp=int(pp), category=category)
    assert rows['METRONOME'] == dict(effect='EFFECT_METRONOME', power=0, source_type='UNKNOWN_T',
        target_type='TYPE_MYSTERY', accuracy=-1, pp=20, category='STATUS')
    assert rows['STRUGGLE'] == dict(effect='EFFECT_RECOIL_HIT', power=50, source_type='UNKNOWN_T',
        target_type='TYPE_MYSTERY', accuracy=-1, pp=1, category='PHYSICAL')
    assert 'const UNKNOWN_T' in files['constants/type_constants.asm']
    assert 'UnknownType: db "???@"' in files['data/types/names.asm']
    commands = files['engine/battle/effect_commands.asm']
    stab = commands.split('BattleCommand_stab:', 1)[1].split('call BattleCheckTypeMatchup', 1)[0]
    assert 'inc a ; cp STRUGGLE\n\tret z' in stab
    metronome = files['engine/battle/move_effects/metronome.asm']
    assert 'call UpdateMoveData\n\tjmp ResetTurn' in metronome
    assert 'call CheckUserMove\n\tjr z, .GetMove' in metronome
    assert '\tdb STRUGGLE ; -1' in files['data/moves/metronome_exception_moves.asm']
    header = f'/* Generated by build_typeless_moves.py from Polished Crystal {source.PIN}. */\n'
    header += '#ifndef GUARD_CONSTANTS_POLISHED_TYPELESS_MOVES_H\n#define GUARD_CONSTANTS_POLISHED_TYPELESS_MOVES_H\n\n'
    header += '// UNKNOWN_T is explicitly mapped; source numeric type IDs are not copied.\n'
    header += ''.join(f'#define POLISHED_{name}_TYPE {row["target_type"]}\n' for name, row in rows.items())
    header += '\n#endif\n'
    manifest = dict(source_repository='Rangi42/polishedcrystal', source_commit=source.PIN,
        source_variant='default (FAITHFUL undefined)', moves=rows,
        selection='Existing B_POLISHED_MOVE_BALANCE / POLISHED_BALANCE compile-time data profile.',
        scope='Static move type identity and summary icons, with focused typeless/called-move regression coverage.',
        runtime_contract=['Struggle skips STAB and type matchups in the pinned source; the native runtime already bypasses both.',
                          'Metronome loads the called move data and restarts execution; its parent type must not replace the called move type.'],
        gaps=['This type-only contract does not certify selection or recoil. The later metronome_struggle.json contract imports the source pool, exceptions, known-slot exclusions and floored recoil.',
              'The source random stream, general damage rounding, PP-exhaustion selection and move bookkeeping remain separate audits.',
              'General type-changing abilities, Conversion/Conversion 2, weather, held-item behavior and AI scoring need separate source audits.',
              'Original source UI layout/art and move animations remain unported. Extra Expansion capabilities remain available.'])
    return {source.ROOT/'include/constants/polished_typeless_moves.h': header,
            source.ROOT/'tools/polished_port/manifests/typeless_moves.json': json.dumps(manifest, indent=2)+'\n'}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, expected in build().items():
        if args.check:
            assert path.read_text() == expected, f'Regenerate {path}'
        else:
            path.write_text(expected)
    print('PASS: pinned Metronome/Struggle UNKNOWN_T mapping and source dispatch contracts')
