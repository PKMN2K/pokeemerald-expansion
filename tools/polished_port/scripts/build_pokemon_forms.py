#!/usr/bin/env python3
"""Map the pinned source's three hidden-form families without changing save IDs."""
import argparse
from functools import cache
import json
import re

import build_pokemon_learnsets as learnsets

OUTPUT = learnsets.ROOT / "src/data/polished_forms.h"
MANIFEST = learnsets.ROOT / "tools/polished_port/manifests/pokemon_forms.json"
FAMILIES = {"EKANS": "EKANS", "ARBOK": "EKANS", "MAGIKARP": "MAGIKARP",
            "GYARADOS": "MAGIKARP", "DUNSPARCE": "DUNSPARCE", "DUDUNSPARCE": "DUNSPARCE"}


@cache
def source_form_values():
    return form_constants(learnsets.sources()["constants/pokemon_constants.asm"])


def wild_mon(level, species, form=None):
    """Preserve explicit plain and hidden forms in imported encounter slots."""
    if form == "NO_FORM":
        return wild_mon(level, species)
    available = set(re.findall(r"\bSPECIES_\w+", (learnsets.ROOT / "include/constants/species.h").read_text()))
    if species in FAMILIES and form is not None:
        value = source_form_values()[form]
        assert 1 <= value <= {"EKANS": 5, "ARBOK": 5, "MAGIKARP": 21,
                              "GYARADOS": 21, "DUNSPARCE": 2, "DUDUNSPARCE": 2}[species]
        if (species in ("EKANS", "DUNSPARCE") or value == 1
                or (species == "GYARADOS" and value < 21)
                or (species == "MAGIKARP" and value == 21)):
            target = "SPECIES_" + species
        else:
            target = learnsets.target_species(species, form, available)
    else:
        target = learnsets.target_species(species, form or "PLAIN_FORM", available)
        value = 1 if form == "PLAIN_FORM" else 0
    result = {"min_level": int(level), "max_level": int(level), "species": target}
    if form is not None:
        result["polished_form"] = value
    return result


def form_constants(text):
    result = {"NO_FORM": 0, "PLAIN_FORM": 1}
    value = None
    for raw in text.splitlines():
        line = raw.split(";", 1)[0].strip()
        match = re.fullmatch(r"ext_const_def (\d+)(?:, (\w+))?", line)
        if match:
            value = int(match[1])
            if match[2]:
                result[match[2]] = value
                value += 1
        elif line.startswith("ext_const ") and value is not None:
            result[line.split()[1]] = value
            value += 1
        elif line.startswith("ext_const_def "):
            # The Gyarados variant starts after all 20 Magikarp patterns.
            assert line == "ext_const_def NUM_MAGIKARP + 1", line
            value = result["MAGIKARP_RAINDROP_FORM"] + 1
    return result


def build():
    files = learnsets.sources()
    forms = form_constants(files["constants/pokemon_constants.asm"])
    # Named ext_const_def aliases consume the initial form value.
    assert forms["ARBOK_JOHTO_FORM"] == forms["ARBOK_KANTO_FORM"] - 1 == 1
    assert forms["DUDUNSPARCE_TWO_SEGMENT_FORM"] == forms["DUDUNSPARCE_THREE_SEGMENT_FORM"] - 1 == 1
    wild = files["engine/battle/random_wild_forms.asm"]
    denominator = int(re.search(r"\.Dudunsparce:\s*;[^\n]*\n\s*ld a, (\d+)", wild)[1])
    assert denominator == 25 and forms["MAGIKARP_RAINDROP_FORM"] == 20 and forms["GYARADOS_RED_FORM"] == 21
    records = []
    identities = json.loads(learnsets.build()[learnsets.MANIFEST])["records"]
    for entry in identities:
        source = entry["source_species"]
        if source not in FAMILIES:
            continue
        form = forms[entry["source_form"]]
        hidden = 0
        if form == 1:
            hidden = {"EKANS": 5, "DUNSPARCE": 2, "GYARADOS": 20, "MAGIKARP": 21}.get(source, 0)
        records.append({"source_species": source, "source_form": entry["source_form"],
                        "target_species": entry["target_species"], "form": form,
                        "base_species": "SPECIES_" + source,
                        "egg_species": "SPECIES_" + FAMILIES[source], "max_hidden_form": hidden})
    assert len(records) == 31
    lines = ["/* Generated by build_pokemon_forms.py from pinned Polished Crystal. */",
             f'#define POLISHED_MAGIKARP_FORMS {forms["MAGIKARP_RAINDROP_FORM"]}',
             f"#define POLISHED_RARE_SEGMENT_DENOMINATOR {denominator}", "",
             "static const struct PolishedFormIdentity sPolishedFormIdentities[] = {"]
    lines += [f'    {{{r["target_species"]}, {r["base_species"]}, {r["egg_species"]}, {r["form"]}, {r["max_hidden_form"]}}},' for r in records]
    lines += ["};", ""]
    manifest = dict(source_commit=learnsets.PIN, source_variant="default; FAITHFUL undefined",
                    records=records, wild_segment_probability={"numerator": 1, "denominator": denominator},
                    storage="Five previously unused encrypted substruct-0 bits; record sizes, existing fields and IDs unchanged. Zero reads the registered identity's form without RNG.",
                    inheritance="Mother/non-Ditto, or an independent equal choice between parents of the same source species (cosmetic/variant IDs normalized). No Everstone requirement.",
                    pinned_source_quirk="DayCare_GenerateEgg keeps the selected form in d across CheckInvalidVariants and both GetFarWord calls, then restores d for NO_FORM offspring. Named Arbok forms and Red Gyarados form 21 survive. Form-21 Magikarp uses plain presentation and evolves back to Red Gyarados.",
                    remaining_gaps=["Original form graphics/palettes/animation metadata.",
                                    "Unown unlock-dependent generation and broader source breeding/creation rules.",
                                    "Unported encounter/trainer maps must supply explicit source forms, including plain form 1, instead of dropping them."])
    return {OUTPUT: "\n".join(lines), MANIFEST: json.dumps(manifest, indent=2) + "\n"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in build().items():
        if args.check:
            assert path.read_text() == content, path
        else:
            path.write_text(content)
    print("PASS: source form identities, wild probabilities and hidden-form storage mapping")


if __name__ == "__main__":
    main()
