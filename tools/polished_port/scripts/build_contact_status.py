#!/usr/bin/env python3
"""Pin contact classification and the five source contact-status abilities."""
import argparse
import json
import re

import build_attack_suite as attacks


def build():
    files, moves, _ = attacks.inventory()
    abilities = files['engine/battle/abilities.asm']
    commands = files['engine/battle/effect_commands.asm']
    contact = files['engine/battle/misc.asm'].split('INCLUDE "data/moves/abnormal_contact_moves.asm"', 1)[0]
    assert 'cp HELD_PROTECTIVE_PADS\n\tjr z, .protective_pads' in contact
    assert 'cp HELD_PUNCHING_GLOVE' in contact and 'farcall IsPunchingMove\n\tret z' in contact
    assert 'cp STRUGGLE\n\tret nc' in contact
    assert 'ld b, PHYSICAL' in contact and 'inc b\n.not_abnormal' in contact
    assert 'ld hl, Moves + MOVE_CATEGORY' in contact
    exceptions = set(re.findall(r'\bdb (\w+)', files['data/moves/abnormal_contact_moves.asm']))
    assert len(exceptions) == 21 and {'DRAINING_KISS', 'PETAL_DANCE'} <= exceptions
    assert 'DEF percent EQUS "* $ff / 100"' in files['macros/data.asm']
    poison_cut = 1 + 33 * 255 // 100
    paralysis_cut = 1 + 66 * 255 // 100
    assert (poison_cut, paralysis_cut) == (85, 169)
    spore = abilities.split('EffectSporeAbility:\n', 1)[1].split('FlameBodyAbility:', 1)[0]
    assert 'call BattleRandom\n\tcp 1 + 33 percent\n\tjr c, PoisonPointAbility\n\tcp 1 + 66 percent\n\tjr c, StaticAbility' in spore
    assert 'cp OVERCOAT' in spore and 'cp HELD_SAFETY_GOGGLES' in spore
    touch = abilities.split('PoisonTouchAbility:\n', 1)[1].split('DoPoisonAbility:', 1)[0]
    assert 'farcall CheckSubHit\n\tret nz\nPoisonPointAbility:\n\tld b, 1' in touch
    afflict = abilities.split('_AfflictStatusAbility:\n', 1)[1].split('CheckNullificationAbilities:', 1)[0]
    assert 'inc b\n\tdec b\n\tjr nz, .enemy_ability' in afflict
    assert 'cp SHIELD_DUST' in afflict and 'cp HELD_COVERT_CLOAK' in afflict
    assert 'ld a, 10\n\tcall BattleRandomRange\n\tcp 3\n\tret nc' in afflict
    assert 'call HasOpponentFainted\n\tret z' in afflict
    assert 'ld a, 3\n\tcall BattleRandomRange\n\tinc a\n.got_status\n\tld [hl], a' in afflict
    assert 'farcall PostStatusWithSynchronize' in afflict
    order = abilities.split('RunContactAbilities:\n', 1)[1].split('UserContactAbilities:', 1)[0]
    assert order.index('call UserAbilityJumptable') < order.index('ld hl, TargetContactAbilities')
    post = commands.split('BattleCommand_posthiteffects:\n', 1)[1].split('CheckStatHerbsAfterIntimidate:', 1)[0]
    assert 'call HasOpponentFainted\n\tcall nz, CheckSubstituteOpp\n\tret nz' in post
    assert post.index('farcall RunHitAbilities') < post.index('cp HELD_ROCKY_HELMET')
    assert 'ld a, 1 << MOVEHIT_SUBSTITUTE\nCheckMoveHitState:' in commands
    assert 'dec [hl]\n\tjr z, .woke_up' in commands

    records = []
    for m in moves:
        makes_contact = m['source_move'] == 'STRUGGLE' or (
            m['source_category'] == ('SPECIAL' if m['source_move'] in exceptions else 'PHYSICAL'))
        records.append(dict(source_move=m['source_move'], target_move=m['target_move'],
                            source_id=m['source_id'], contact=makes_contact,
                            direct_damage=m['source_effect'] in attacks.DIRECT))
    prefix = f'/* Generated by build_contact_status.py from Polished Crystal {attacks.source.PIN}. */\n'
    header = prefix + '/* Zero: optional move; one: source noncontact; two: source contact. */\n'
    header += 'static const u8 sPolishedContactStatusMoves[MOVES_COUNT] = {\n'
    header += ''.join(f"    [{m['target_move']}] = {2 if m['contact'] else 1},\n" for m in records)
    header += '};\n'
    constants = prefix + '#define POLISHED_SPORE_POISON_CUTOFF 85\n#define POLISHED_SPORE_PARALYSIS_CUTOFF 169\n#define POLISHED_CONTACT_SLEEP_MAX 3\n'
    vectors = prefix + 'struct PolishedContactVector { enum Move move; bool8 contact; };\n'
    vectors += 'static const struct PolishedContactVector sPolishedContactVectors[] = {\n'
    vectors += ''.join(f"    {{{m['target_move']}, {'TRUE' if m['contact'] else 'FALSE'}}},\n" for m in records if m['direct_damage'])
    vectors += '};\n'
    report = dict(source_repository='Rangi42/polishedcrystal', source_commit=attacks.source.PIN,
        source_variant='default (FAITHFUL undefined)', moves=records,
        effect_spore=dict(selection_range=256, poison_bytes=85, paralysis_bytes=84, sleep_bytes=87,
            activation_numerator=3, activation_denominator=10,
            joint_probabilities={'poison': [255, 2560], 'paralysis': [252, 2560], 'sleep': [261, 2560]},
            initial_sleep_counters=[1, 2, 3]),
        rules=[
            'Contact uses source physical/special category and 21 exceptions; Struggle is contact. Protective Pads suppresses both sides; Punching Glove suppresses punches.',
            'Poison Touch is evaluated before the defender contact ability. Its source entry sets b=1, bypassing the b=0 Shield Dust/Covert Cloak checks despite the nearby comment.',
            'All five status abilities use a separate three-in-ten activation decision; Effect Spore first chooses poison/paralysis/sleep with the byte thresholds 85 and 169.',
            'Defender contact abilities can run after Substitute breaks or their holder faints. Poison Touch checks the hit Substitute marker and stays blocked on a breaking hit.',
            'Effect Spore stores counters one through three. The next action decrements first, so without Early Bird it blocks zero through two future actions before waking.',
            'Status eligibility still checks existing status, type/ability prevention and Safeguard. Effect Spore additionally checks Grass, Overcoat and Safety Goggles.'],
        scope='Mapped source moves in ordinary singles without either active gimmick; Effect Spore, Poison Point, Static, Flame Body and Poison Touch only.',
        gaps=[
            'This is not a general contact-engine or status-engine import. Other contact abilities/items, all status-immunity configuration variants, simultaneous curing/Synchronize chains, recoil/self-faint and global faint/proc ordering need separate audits.',
            'Original RNG stream/call alignment, battle animation/message timing and AI estimates remain open. Expansion-only moves, formats, gimmicks and optional ability/terrain prevention retain native behavior.'])
    root = attacks.source.ROOT
    return {root/'src/data/polished_contact_status.h': header,
            root/'include/constants/polished_contact_status.h': constants,
            root/'test/battle/ability/polished_contact_vectors.h': vectors,
            root/'tools/polished_port/manifests/contact_status.json': json.dumps(report, indent=2)+'\n'}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, expected in build().items():
        if args.check:
            assert path.read_text() == expected, f'Regenerate {path}'
        else:
            path.write_text(expected)
    print('PASS: 255 contact identities, five status abilities, source selection, sleep and hit boundaries')
