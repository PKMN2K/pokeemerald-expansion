#!/usr/bin/env python3
"""Resolve the source's wild gender ratio using the lead's form and extension byte."""
import argparse
import hashlib
import json
from pathlib import Path
import re

import build_pokemon_forms as forms
import build_pokemon_base_data as species

ROOT = species.ROOT
FIXTURE = ROOT/'tools/polished_port/fixtures/battle_logic/wild_gender.json'
OUT = ROOT/'src/data/polished_wild_gender.h'
ROM_DIGEST = 'f06dbebe3fd20db54e7804605f7a55ad05b8ca203c62209705290d8880864803'
SYM_DIGEST = 'be1ca87ad487ade20701ed71fcae4e99bf16b908af727b84575c862b73ea2955'


def reference(rom_path, sym_path):
    rom, sym = rom_path.read_bytes(), sym_path.read_bytes()
    assert hashlib.sha256(rom).hexdigest() == ROM_DIGEST and hashlib.sha256(sym).hexdigest() == SYM_DIGEST
    def address(symbol):
        match = re.search(rb'^([0-9a-f]+):([0-9a-f]+) '+re.escape(symbol.encode())+rb'$', sym, re.M|re.I)
        return tuple(int(x, 16) for x in match.groups())
    _, fn = address('GetGenderRatio.Function')
    bank, base = address('BaseData')
    # GetGenderRatio calls GetSpeciesAndFormIndex, then indexes a ROMX bank
    # with ld a,BASE_DATA_SIZE / ld hl,BaseData+BASE_GENDER / rst AddNTimes.
    assert rom[fn+5] == 0x3e and rom[fn+7] == 0x21 and rom[fn+10] == 0xdf
    stride = rom[fn+6]
    first = int.from_bytes(rom[fn+8:fn+10], 'little')
    assert first - base == 12
    ratios = [rom[bank*0x4000 + (addr&0x3fff)] >> 4 for addr in range(first, 0x8000, stride)]
    _, offset = address('VariantSpeciesAndFormTable')
    variants = []
    while rom[offset]:
        variants.append(list(rom[offset:offset+2]))
        offset += 2
    return dict(source_commit=forms.learnsets.PIN, rom_sha256=ROM_DIGEST, symbols_sha256=SYM_DIGEST,
                ratio_nibbles=''.join(format(r,'x') for r in ratios), variant_species_forms=variants)


def build(fix):
    assert fix['source_commit'] == forms.learnsets.PIN and fix['rom_sha256'] == ROM_DIGEST
    rows = json.loads(species.MANIFEST.read_text())['records']
    ratios = [int(n,16) for n in fix['ratio_nibbles']]
    variants = fix['variant_species_forms']
    assert len(ratios) == 398 and len(variants) == 46
    constants = forms.learnsets.sources()['constants/pokemon_constants.asm']
    numbers = forms.form_constants(constants)
    numbers.update({k:int(v) for k,v in re.findall(r'DEF (\w+_FORM) EQU (\d+)', constants)})
    base = {r['source_species']:r['source_table_index'] for r in rows if r['source_form']=='PLAIN_FORM'}
    assert max(base.values()) == 291
    lines = ['/* Polished Crystal v3.2.3, generated by build_wild_gender.py. */',
             'static const struct { u8 species, form; } sWildGenderIdentities[NUM_SPECIES] = {']
    for row in rows:
        index = base[row['source_species']]
        low, form = index & 255, (32 if index > 255 else 0) | numbers[row['source_form']]
        found = next((i for i,(s,f) in enumerate(variants) if s == low and f == form), None)
        slot = index - 1 if found is None else 291 + found
        expected = {'GENDER_F0':0,'GENDER_F12_5':1,'GENDER_F25':2,'GENDER_F37_5':3,'GENDER_F50':4,
                    'GENDER_F62_5':5,'GENDER_F75':6,'GENDER_F87_5':7,'GENDER_F100':8,'GENDER_UNKNOWN':15}
        assert ratios[slot] == expected[row['gender']], row
        lines.append(f'    [{row["target_species"]}] = {{{low}, {form}}},')
    lines.extend(['};','static const u8 sWildGenderRatios[] = {'])
    for offset in range(0,len(ratios),24):
        lines.append('    '+', '.join(map(str,ratios[offset:offset+24]))+',')
    lines.extend(['};','static const struct { u8 species, form, ratio; } sWildGenderVariants[] = {'])
    for i,(low,form) in enumerate(variants):
        regular = low - 1 + (256 if form & 32 else 0)
        if ratios[291+i] != ratios[regular]:
            lines.append(f'    {{{low}, {form}, {ratios[291+i]}}},')
    return '\n'.join(lines+['};',''])


if __name__ == '__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--reference',nargs=2,type=Path,metavar=('ROM','SYM'))
    p.add_argument('--check',action='store_true')
    args=p.parse_args()
    if args.reference:
        FIXTURE.write_text(json.dumps(reference(*args.reference),separators=(',',':'))+'\n')
    encoded=FIXTURE.read_bytes()
    assert hashlib.sha256(encoded).hexdigest() == '3161a2436ccb131fd6c360bbadf81adb993a1d61dfcabcc2733de6a585569c6e'
    content=build(json.loads(encoded))
    if args.check:
        assert OUT.read_text() == content, f'Regenerate {OUT}'
    else:
        OUT.write_text(content)
    print('PASS: 391 source identities and 398 ROM-backed wild gender ratios')
