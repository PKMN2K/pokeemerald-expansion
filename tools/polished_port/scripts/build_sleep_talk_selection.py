#!/usr/bin/env python3
"""Pin Sleep Talk's known-move eligibility and cleared last-move history."""
import argparse
import json
import re

import build_pokemon_learnsets as source


def build():
    files = source.sources()
    command = files['engine/battle/move_effects/sleep_talk.asm']
    core = files['engine/battle/core.asm']
    excluded = re.findall(r'^\s*db (EFFECT_\w+)', files['data/moves/sleep_talk_exception_move_effects.asm'], re.M)
    assert excluded == ['EFFECT_METRONOME', 'EFFECT_SKETCH', 'EFFECT_SLEEP_TALK', 'EFFECT_SOLAR_BEAM', 'EFFECT_FLY']
    # GetDisableEncoreMoves returns d=Disable, e=Encore. Sleep Talk immediately
    # replaces e with its eligibility bitset, then only compares moves with d.
    assert 'Sets d to disabled move ID and e to encored/choiced move ID.' in core
    assert 'farcall GetDisableEncoreMoves\n\tlb bc, NUM_MOVES, 0\n\tld e, c' in command
    loop = command.split('\n.usable_move_loop\n', 1)[1].split('\n.end_loop\n', 1)[0]
    assert '\tcp d\n\tjr z, .next_move' in loop
    assert 'farcall GetMoveEffect' in loop and 'call IsInByteArray' in loop
    assert 'PP' not in command and 'CHOICE' not in command
    assert 'and SLP_MASK\n\tjr z, .fail' in command
    assert 'ld a, c\n\tand a\n\tjr z, .fail\n\tcall RandomRange' in command
    assert 'call UpdateMoveData\n\tpop af\n\tld [wCurMoveNum], a\n\tjmp ResetTurn' in command
    assert command.startswith('BattleCommand_sleeptalk:\n\tcall ClearLastMove\n')
    commands = files['engine/battle/effect_commands.asm']
    clear = commands.split('\nClearLastMove:\n', 1)[1].split('\nResetActorDisable:', 1)[0]
    assert 'ld a, BATTLE_VARS_LAST_COUNTER_MOVE' in clear and 'ld a, BATTLE_VARS_LAST_MOVE' in clear
    assert clear.count('\txor a\n\tld [hl], a') == 2
    assert '\nResetTurn:\n\tld a, 1\n_ResetTurn:' in commands
    display = files['engine/battle/used_move_text.asm']
    assert 'dec a\n\tjr z, .charging' in display
    assert display.index('jr z, .charging') < display.index('ld a, BATTLE_VARS_LAST_COUNTER_MOVE')
    reaction = files['engine/battle/move_effects/encore_disable.asm']
    assert 'ld a, BATTLE_VARS_LAST_COUNTER_MOVE_OPP\n\tcall GetBattleVar\n\tand a\n\tjr z, .failed' in reaction
    rows = [[v.strip() for v in line[5:].split(',')] for line in
            source.default_lines(files['data/moves/moves.asm'].split('Moves::', 1)[1]) if line.startswith('move ')]
    identities = source.move_identities(files)[1:]
    records = []
    for identity, row in zip(identities, rows, strict=True):
        assert identity['source_move'] == row[0]
        # Struggle is never a source known move. Its native defensive ban is
        # retained; the source comment is not an executable ban in this loop.
        if row[0] == 'STRUGGLE':
            continue
        records.append(dict(**identity, source_effect=row[1], eligible=row[1] not in excluded))
    assert len(records) == 254
    assert {r['source_move'] for r in records if not r['eligible']} == {'METRONOME', 'SKETCH', 'SLEEP_TALK', 'SOLAR_BEAM', 'FLY', 'DIG'}
    header = f'/* Source expectations from Polished Crystal {source.PIN}; generated by build_sleep_talk_selection.py. */\n'
    header += '#ifndef GUARD_TEST_POLISHED_SLEEP_TALK_H\n#define GUARD_TEST_POLISHED_SLEEP_TALK_H\n\n'
    header += 'static const struct { enum Move move; bool8 eligible; } sSourceSleepTalkMoves[] = {\n'
    header += ''.join(f'    {{{r["target_move"]}, {"TRUE" if r["eligible"] else "FALSE"}}},\n' for r in records)
    header += '};\n\n#endif\n'
    report = dict(source_repository='Rangi42/polishedcrystal', source_commit=source.PIN,
        source_variant='default (FAITHFUL undefined)', profile='B_POLISHED_MOVE_BALANCE',
        scope='Sleep Talk static candidate eligibility for source known moves, cleared last-move history and ordinary singles Disable/Choice/PP regressions.',
        excluded_effects=excluded, candidates=records,
        runtime_contract=dict(disabled_move_excluded=True, last_counter_move_cleared=True,
            called_move_does_not_restore_last_move=True, following_disable_and_encore_fail=True,
            choice_ignored_for_called_move=True, called_move_pp_ignored=True, parent_pp_consumed=True),
        gaps=['The native random stream, rejection sampling and slot order remain: this suite does not port source RandomRange or global RNG call timing.',
              'Struggle is not a legal source known move; its defensive native ban remains, without claiming an executable source-list ban.',
              'Sleep duration, full Encore/Disable timing and interrupted-turn/called-move bookkeeping, called effects, smart AI, animations and UI remain separate audits.',
              'The source ignores Encore during candidate selection, but clears the history needed to Encore Sleep Talk; artificial pre-encored Sleep Talk states are not imported.',
              'Expansion-only moves, abilities and formats retain native framework rules.'])
    return {source.ROOT/'include/test/polished_sleep_talk.h': header,
            source.ROOT/'tools/polished_port/manifests/sleep_talk_selection.json': json.dumps(report, indent=2)+'\n'}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, expected in build().items():
        if args.check:
            assert path.read_text() == expected, f'Regenerate {path}'
        else:
            path.write_text(expected)
    print('PASS: pinned Sleep Talk eligibility for 254 source known moves and cleared last-move history')
