#!/usr/bin/env python3
"""Pin the seven source multi-hit attacks, their selection and loop boundaries."""
import argparse
import json

import build_attack_suite as attacks


def build():
    files, moves, scripts = attacks.inventory()
    selected = [m for m in moves if m['source_effect'] in ('EFFECT_MULTI_HIT', 'EFFECT_DOUBLE_HIT')]
    assert [m['source_move'] for m in selected] == [
        'DOUBLE_SLAP', 'DOUBLE_KICK', 'PIN_MISSILE', 'ROCK_BLAST', 'ICICLE_SPEAR', 'FURY_STRIKES', 'BONEMERANG']
    expected = ['checkobedience', 'usedmovetext', 'doturn', 'hastarget', 'startloop',
                'lowersub', 'checkhit', 'checkpriority', 'critical', 'damagestats',
                'damagecalc', 'stab', 'damagevariation', 'clearmissdamage',
                'moveanimnosub', 'failuretext', 'applydamage', 'criticaltext',
                'cleartext', 'postfainteffects', 'posthiteffects', 'supereffectivetext',
                'endloop', 'raisesub', 'endmove']
    for effect in ('EFFECT_MULTI_HIT', 'EFFECT_DOUBLE_HIT'):
        assert scripts[effect] == dict(label='MultiHit', commands=expected)
    commands = files['engine/battle/effect_commands.asm']
    start = commands.split('BattleCommand_startloop:\n', 1)[1].split('BattleCommand_supereffectivetext:', 1)[0]
    assert start.index('cp EFFECT_DOUBLE_HIT') < start.index('cp SKILL_LINK') < start.index('cp HELD_LOADED_DICE')
    assert 'cp EFFECT_DOUBLE_HIT\n\tld a, 2\n\tjr z, .got_count' in start
    assert 'cp SKILL_LINK\n\tld a, 5\n\tjr z, .got_count' in start
    assert 'call BattleRandom\n\tand 1\n\tadd 4' in start
    assert 'ld a, 6\n\tcall BattleRandomRange\n\tcp 4\n\tjr c, .random_ok\n\tsub 4\n.random_ok\n\tadd 2' in start
    end = commands.split('BattleCommand_endloop:\n', 1)[1].split('BattleCommand_flinchtarget:', 1)[0]
    assert 'ld b, critical_command\n\tjmp SkipToBattleCommandBackwards' in end
    assert 'SLP' not in end and 'FRZ' not in end
    pp = commands.split('BattleConsumePP:\n', 1)[1].split('BattleCommand_critical:', 1)[0]
    assert 'and 1 << SUBSTATUS_IN_LOOP | 1 << SUBSTATUS_RAMPAGE | 1 << SUBSTATUS_CHARGED | 1 << SUBSTATUS_ROLLOUT\n\tret nz' in pp
    post = commands.split('BattleCommand_posthiteffects:\n', 1)[1].split('CheckStatHerbsAfterIntimidate:', 1)[0]
    assert 'farcall RunHitAbilities' in post
    assert 'call HasUserFainted\n\tjr nz, .check_parental_bond\n\tcall EndMoveEffect' in post
    assert 'SLP_MASK' not in post and 'EndMultihit' not in post
    status = files['engine/battle/abilities.asm'].split('_AfflictStatusAbility:\n', 1)[1].split('CheckNullificationAbilities:', 1)[0]
    assert 'ld [hl], a' in status and 'farcall PostStatusWithSynchronize' in status
    assert 'EndMoveEffect' not in status and 'EndMultihit' not in status
    faint = commands.split('BattleCommand_postfainteffects:\n', 1)[1].split('BattleCommand_posthiteffects:', 1)[0]
    assert 'call nz, EndMultihit' in faint
    header = [f'/* Generated by build_multihit.py from Polished Crystal {attacks.source.PIN}. */',
              'static const u8 sPolishedMultiHitKind[MOVES_COUNT] = {']
    for m in selected:
        header.append(f"    [{m['target_move']}] = {2 if m['source_effect'] == 'EFFECT_DOUBLE_HIT' else 1},")
    header += ['};', 'static const u8 sPolishedMultiHitCounts[] = {2, 3, 4, 5, 2, 3};', '']
    report = dict(source_repository='Rangi42/polishedcrystal', source_commit=attacks.source.PIN,
        source_variant='default (FAITHFUL undefined)', moves=selected,
        source_slots=[2, 3, 4, 5, 2, 3], source_weights={'2': 2, '3': 2, '4': 1, '5': 1},
        rules=[
            'Double Kick and Bonemerang choose two hits before checking Skill Link or Loaded Dice.',
            'The five variable attacks choose five with active Skill Link; otherwise Loaded Dice chooses four/five equally; otherwise six equal slots map to 2,3,4,5,2,3.',
            'PP, action cancellation, accuracy and priority checks occur once. Each later hit returns to critical, recalculating damage and its random variation.',
            'Target fainting ends the loop; attacker fainting aborts the move. Intact/broken Substitute is processed separately on each hit.',
            'Effect Spore can inflict sleep between hits, but the loop does not recheck sleep. Remaining strikes complete and the next action observes sleep.',
            'Per-hit contact/held-item reactions can change HP and stats before the next strike. Parental Bond does not add another strike to an existing multi-hit loop.'],
        adapter='Select all mapped variable attacks through the six source slots and permit the mapped loop to continue through newly inflicted sleep, in ordinary source singles without either active gimmick. Preserve original Fury Strikes distribution outside that scope.',
        limits=[
            'Effect Spore selection/activation, sleep counters and scoped contact-status boundaries are covered separately in contact_status.json. These multi-hit tests force sleep to isolate loop continuation; complete contact eligibility/order remains open.',
            'Broken-Substitute ability/proc eligibility, Rocky Helmet faint-order/proc interactions, damage/critical formulas, per-hit RNG stream, deferred switching, AI estimates and original battle animation/message sequencing remain open.',
            'Optional moves, doubles and either active gimmick retain native loop rules. Existing custom Fury Strikes hit-count behavior remains available outside the source profile.'])
    return {attacks.source.ROOT/'src/data/polished_multihit.h': '\n'.join(header),
            attacks.source.ROOT/'tools/polished_port/manifests/multihit.json': json.dumps(report, indent=2)+'\n'}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, expected in build().items():
        if args.check:
            assert path.read_text() == expected, f'Regenerate {path}'
        else:
            path.write_text(expected)
    print('PASS: seven source multi-hit identities, six selection slots, priority and loop boundaries')
