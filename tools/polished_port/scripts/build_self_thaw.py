#!/usr/bin/env python3
"""Pin source self-thaw identities and their position before action blockers."""
import argparse
import json
import re

import build_pokemon_learnsets as source
import build_freeze as freeze


def build():
    freeze.build()
    files = source.sources()
    commands = files['engine/battle/effect_commands.asm']
    turn = commands.split('\nBattleCommand_checkturn:', 1)[1].split('\nEndTurn:', 1)[0]
    labels = ['.no_recharge', '.not_flinched', '.not_asleep', '.thaw',
              '.not_frozen', '.not_confused', '.not_infatuated', '.not_disabled']
    positions = [turn.index('\n'+label+'\n') for label in labels]
    assert positions == sorted(positions)
    recharge = turn.split('\n.no_recharge\n', 1)[0]
    assert 'bit SUBSTATUS_RECHARGE, [hl]' in recharge
    assert 'call CantMove\n\tjmp EndTurn' in recharge
    flinch = turn.split('\n.no_recharge\n', 1)[1].split('\n.not_flinched\n', 1)[0]
    assert [line for line in source.default_lines(flinch) if line] == [
        'ld a, BATTLE_VARS_SUBSTATUS4', 'call GetBattleVarAddr',
        'bit SUBSTATUS_FLINCHED, [hl]', 'jr z, .not_flinched',
        'res SUBSTATUS_FLINCHED, [hl]', 'call GetTrueUserAbility', 'cp INNER_FOCUS',
        'jr z, .not_flinched', 'push af', 'ld hl, FlinchedText', 'call StdBattleTextbox',
        'pop af', 'cp STEADFAST', 'jr nz, .skip_steadfast', 'farcall SteadfastAbility',
        '.skip_steadfast', 'call CantMove', 'jmp EndTurn']
    frozen = turn.split('\n.not_asleep\n', 1)[1].split('\n.not_frozen\n', 1)[0]
    names = re.findall(r'\tcp ([A-Z_]+)\n\tjr z, \.thaw', frozen)
    assert names == ['SACRED_FIRE', 'SCALD', 'FLARE_BLITZ']
    identities = {row['source_move']: row for row in source.move_identities(files)[1:]}
    selected = [identities[name] for name in names]
    confusion = turn.split('\n.not_frozen\n', 1)[1].split('\n.not_confused\n', 1)[0]
    assert 'call HitConfusion\n\tcall CantMove\n\tjr EndTurn' in confusion
    attract = turn.split('\n.not_confused\n', 1)[1].split('\n.not_infatuated\n', 1)[0]
    assert 'ld hl, InfatuationText\n\tcall StdBattleTextbox\n\tcall CantMove\n\tjr EndTurn' in attract
    disabled = turn.split('\n.not_infatuated\n', 1)[1].split('\n.not_disabled\n', 1)[0]
    assert 'call MoveDisabled\n\tcall CantMove\n\tjr EndTurn' in disabled
    assert frozen.endswith('\n.thaw\n\tcall DefrostUser\n')
    report = dict(source_repository='Rangi42/polishedcrystal', source_commit=source.PIN,
        source_variant='default (FAITHFUL undefined)', profile='B_POLISHED_MOVE_BALANCE',
        scope='Self-thaw before Disable, confusion and infatuation for the three source moves in singles without either active gimmick.',
        moves=selected,
        rules=['Recharge and effective flinch prevent the source freeze/self-thaw stage.',
               'Sacred Fire, Scald and Flare Blitz are selected by move identity, without a battle-type gate or random thaw roll.',
               'DefrostUser clears freeze and updates the party before confusion, infatuation and Disable are evaluated.',
               'A later action blocker can prevent the attack and PP consumption, but the battler remains thawed.'],
        adapter='Run the existing thaw status update and script immediately before the Disable canceler, after flinch. Resume that same canceler after the thaw script, so Disable still applies and clearing freeze prevents a duplicate thaw.',
        gaps=['This ports the self-thaw relation to these blockers, not their relative ordering, source RNG stream, confusion damage or original presentation.',
              'Obedience, PP validation, Truant, other earlier native cancelers and the complete action sequence remain separate audits.',
              'Optional self-thaw moves, Frostbite, doubles and either active gimmick retain their existing ordering. Incoming thaw attacks and full freeze eligibility remain separate work.'])
    header = f'/* Generated by build_self_thaw.py from Polished Crystal {source.PIN}. */\n'
    header += 'static const u8 sPolishedSelfThawMoves[MOVES_COUNT] = {\n'
    header += ''.join(f"    [{row['target_move']}] = TRUE,\n" for row in selected)
    header += '};\n'
    return {source.ROOT/'src/data/polished_self_thaw.h': header,
            source.ROOT/'tools/polished_port/manifests/self_thaw.json': json.dumps(report, indent=2)+'\n'}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, expected in build().items():
        if args.check:
            assert path.read_text() == expected, f'Regenerate {path}'
        else:
            path.write_text(expected)
    print('PASS: three pinned self-thaw moves clear freeze before confusion, infatuation and Disable')
