#!/usr/bin/env python3
"""Generate Bag HP-recovery amounts from the pinned default source."""
import argparse
import re

import build_pokemon_learnsets as source
from build_pokemon_held_items import catalog, sources

OUTPUT = source.ROOT / "src/data/polished_item_healing.h"
ALIASES = {"ENERGYPOWDER": "ENERGY_POWDER"}


def build():
    items = catalog(sources())
    files = source.sources()
    effects = files["engine/items/item_effects.asm"]
    # Select the actual HP-use handlers, not every item with a numeric param.
    names = re.findall(r"dw (?:RestoreHPEffect|EnergyPowder|EnergyRoot)\s*; (\w+)", effects)
    assert len(names) == len(set(names)) == 14
    healing = effects.split("GetHealingItemAmount:", 1)[1].split("FreshSnackFunction:", 1)[0]
    assert "cp SITRUS_BERRY\n\tjr z, .sitrus_berry" in healing
    assert "cp FIGY_BERRY\n\tjr z, .figy_berry" in healing
    assert "cp -1\n\tret nz\n\tld de, 999" in healing
    assert "call GetThirdBC" in healing.split("\n.figy_berry\n", 1)[1].split("\n.sitrus_berry\n", 1)[0]
    quarter = healing.split("\n.sitrus_berry\n", 1)[1].split("\n.set_de_to_hp\n", 1)[0]
    assert quarter.count("srl d\n\trr e") == 2 and "ld e, 1" in quarter
    third = files["home/battle.asm"].split("GetThirdBC:", 1)[1].split("GetSixteenthMaxHP::", 1)[0]
    assert third.count("dec bc") == 3 and "ret nz\n\tinc c\n\tret" in third
    lines = ["/* Generated by build_item_healing.py from Polished Crystal " + source.PIN + ". */",
             "/* Zero amount/divisor is unmapped; Max Potion's source parameter -1 means 999 HP. */",
             "static const struct PolishedItemHealing sPolishedItemHealing[ITEMS_COUNT] = {"]
    for name in names:
        attrs = items[name]["source_attributes"]
        assert attrs[4:] == ["ITEMMENU_PARTY", "ITEMMENU_PARTY"], name
        param = int(attrs[2])
        divisor = {"SITRUS_BERRY": 4, "FIGY_BERRY": 3}.get(name, 0)
        if divisor:
            assert param == 0
        else:
            assert param == -1 or 0 < param < 251
        amount = 999 if param == -1 else param
        lines.append(f"    [ITEM_{ALIASES.get(name, name)}] = {{{amount}, {divisor}}},")
    lines += ["};", ""]
    return "\n".join(lines).encode()


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = build()
    if args.check:
        assert OUTPUT.read_bytes() == data, "Regenerate source item healing"
    else:
        OUTPUT.write_bytes(data)
    print("PASS: 14 source HP-use items, fixed/quarter/third recovery and menu availability")
