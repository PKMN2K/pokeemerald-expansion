#!/usr/bin/env python3
"""Import pinned default-source evolution rows and shared engine metadata."""
import argparse
import json
import re
from pathlib import Path

import build_pokemon_learnsets as learnsets

ROOT = learnsets.ROOT
OUTPUT = ROOT / "src/data/polished_evolutions.h"
MANIFEST = ROOT / "tools/polished_port/manifests/pokemon_evolutions.json"
LANDMARKS = ("MAGNET_TUNNEL", "DIM_CAVE", "ILEX_FOREST", "ICE_PATH",
             "SINJOH_RUINS", "MYSTRI_STAGE", "RUGGED_ROAD", "SNOWTOP_MOUNTAIN")
METHODS = set("LEVEL ITEM TRADE HOLDING HAPPINESS STAT LOCATION MOVE CRIT PARTY".split())


def parse(text):
    groups = {}
    current = None
    for line in learnsets.default_lines(text.split("EvosAttacks::", 1)[1]):
        if line.startswith("evos_attacks "):
            current = line.split()[1]
            assert current not in groups
            groups[current] = []
        elif line.endswith("EvosAttacks:"):
            # These labels start AFTER the preceding species' evolution rows.
            current = line.removesuffix("EvosAttacks:")
            assert current in ("MrRime", "Farigiraf", "Egg"), current
            groups[current] = []
        elif line.startswith("evo_data "):
            parts = [p.strip() for p in line.removeprefix("evo_data ").split(",")]
            method = parts.pop(0).removeprefix("EVOLVE_")
            assert method in METHODS, method
            argument = parts.pop(0)
            extra = parts.pop(0) if method in ("STAT", "HOLDING") else "0"
            assert len(parts) in (1, 2), line
            groups[current].append(dict(method=method, argument=argument, extra=extra,
                                        species=parts[0], form=parts[1] if len(parts) == 2 else "PLAIN_FORM"))
        else:
            assert not line or line.startswith(("learnset ", "db ")), line
    return groups


def build():
    files = learnsets.sources()
    groups = parse(files["data/pokemon/evos_attacks.asm"])
    identity = json.loads(learnsets.build()[learnsets.MANIFEST])["records"]
    available = set(re.findall(r"\bSPECIES_\w+", (ROOT / "include/constants/species.h").read_text()))
    items = set(re.findall(r"\bITEM_\w+", (ROOT / "include/constants/items.h").read_text()))
    moves = set(re.findall(r"\bMOVE_\w+", (ROOT / "include/constants/moves.h").read_text()))
    friendship = int(re.search(r"HAPPINESS_TO_EVOLVE\s+EQU\s+(\d+)", files["constants/pokemon_data_constants.asm"])[1])
    lines = ["/* Generated by build_pokemon_evolutions.py; pinned default Polished Crystal. */", ""]
    records, bindings, arrays = [], [], {}
    for entry in identity:
        source = groups[entry["source_learnset"]]
        if entry["target_species"] == "SPECIES_PICHU_SPIKY_EARED":
            source = []  # Explicit engine/pokemon/evolve.asm exception.
        key = json.dumps(source, sort_keys=True)
        if key not in arrays:
            name = "sPolishedEvos_" + entry["target_species"].removeprefix("SPECIES_")
            arrays[key] = name
            raw, metadata = [], []
            for row in source:
                method, argument, extra = row["method"], row["argument"], row["extra"]
                form = row["form"]
                # Source NO_FORM preserves hidden form bits. The current registry
                # represents ordinary Ekans/Dunsparce; their hidden variants are
                # explicitly tracked as a remaining creation/save-data gap.
                target = learnsets.target_species(row["species"], "PLAIN_FORM" if form == "NO_FORM" else form, available)
                native_method, level, conditions = "EVO_LEVEL", "1", []
                if method in ("ITEM", "TRADE", "HOLDING"):
                    argument = "ITEM_" + ("POLISHED_ODD_SOUVENIR" if argument == "ODD_SOUVENIR" else argument)
                    assert argument in items, argument
                    if method == "ITEM" or argument == "ITEM_LINKING_CORD":
                        native_method, level = "EVO_ITEM", argument
                    else:
                        conditions.append(("IF_HOLD_ITEM", argument))
                    if method == "HOLDING":
                        extra = "POLISHED_" + extra
                        if row["extra"] != "TR_ANYTIME":
                            conditions.append(("IF_POLISHED_TIME", extra))
                elif method in ("LEVEL", "STAT"):
                    assert argument.isdecimal() and 1 <= int(argument) <= 100
                    level = argument
                    if method == "STAT":
                        assert extra in ("ATK_GT_DEF", "ATK_EQ_DEF", "ATK_LT_DEF")
                        conditions.append(("IF_" + extra, "0"))
                        extra = "POLISHED_" + extra
                elif method == "HAPPINESS":
                    assert argument in ("TR_ANYTIME", "TR_MORNDAY", "TR_EVENITE")
                    argument = "POLISHED_" + argument
                    conditions.append(("IF_MIN_FRIENDSHIP", str(friendship)))
                    if row["argument"] != "TR_ANYTIME":
                        conditions.append(("IF_POLISHED_TIME", argument))
                elif method == "LOCATION":
                    assert argument in LANDMARKS, argument
                    argument = "POLISHED_LANDMARK_" + argument
                    conditions.append(("IF_POLISHED_LANDMARK", argument))
                elif method == "MOVE":
                    argument = "MOVE_" + learnsets.MOVE_ALIASES.get(argument, argument)
                    assert argument in moves, argument
                    conditions.append(("IF_KNOWS_MOVE", argument))
                elif method == "PARTY":
                    argument = learnsets.target_species(argument, "PLAIN_FORM", available)
                    conditions.append(("IF_SPECIES_IN_PARTY", argument))
                elif method == "CRIT":
                    assert argument == "TR_ANYTIME"
                    argument, native_method = "3", "EVO_BATTLE_END"
                    conditions.append(("IF_CRITICAL_HITS_GE", "3"))
                raw.append(f"    {{POLISHED_EVOLVE_{method}, {argument}, {extra}, {target}}},")
                params = "NULL"
                if conditions:
                    params = "(const struct EvolutionParam[]) {" + ", ".join("{" + a + ", " + b + "}" for a, b in conditions) + ", {CONDITIONS_END}}"
                metadata.append(f"    {{{native_method}, {level}, {target}, {params}}},")
            lines += [f"static const struct PolishedEvolution {name}Rules[] = {{"] + raw + ["    {POLISHED_EVOLVE_END},", "};"]
            lines += [f"static const struct Evolution {name}[] = {{"] + metadata + ["    {EVOLUTIONS_END},", "};", ""]
        bindings.append((entry["target_species"], arrays[key]))
        records.append({k: entry[k] for k in ("source_species", "source_form", "source_learnset", "target_species")} | {"rules": source})
    lines += ["static const struct PolishedEvolution *const sPolishedEvolutionRules[NUM_SPECIES] = {"]
    lines += [f"    [{species}] = {name}Rules," for species, name in bindings] + ["};", ""]
    lines += ["static const struct Evolution *const sPolishedEvolutionMetadata[NUM_SPECIES] = {"]
    lines += [f"    [{species}] = {name}," for species, name in bindings] + ["};", ""]
    lines += [f"#define POLISHED_EVOLUTION_FRIENDSHIP {friendship}", ""]
    # Match source map identities, never substitute a Hoenn location with a
    # similar name. New ported maps register automatically upon regeneration.
    locations = []
    for line in files["data/maps/maps.asm"].splitlines():
        match = re.match(r"\s*map (\w+), [^,]+, [^,]+, [^,]+, (\w+),", line)
        if match and match[2] in LANDMARKS:
            path = ROOT / "data/maps" / ("Polished" + match[1]) / "map.json"
            locations.append(dict(source_map=match[1], landmark=match[2], target_map=json.loads(path.read_text())["id"] if path.exists() else None))
    lines += ["static const struct PolishedEvolutionLocation sPolishedEvolutionLocations[] = {"]
    lines += [f'    {{MAP_GROUP({r["target_map"]}), MAP_NUM({r["target_map"]}), POLISHED_LANDMARK_{r["landmark"]}}},' for r in locations if r["target_map"]]
    lines += ["    {0, 0, POLISHED_LANDMARK_NONE},", "};", ""]
    manifest = dict(source_commit=learnsets.PIN, source_variant="default; FAITHFUL undefined",
                    mapped_target_count=len(records), source_evolution_row_count=sum(map(len, groups.values())),
                    friendship_threshold=friendship, locations=locations,
                    remaining_gaps=["Hidden Ekans/Dunsparce and inherited Magikarp/Gyarados form bits need a creation/inheritance/save adapter; ordinary registered identities retain plain evolutions.",
                                    "Evolution landmarks await their campaign maps; no Hoenn replacements are enabled.",
                                    "Default-source mid-trainer-battle evolution timing is not yet implemented; current runtime evolves after the battle.",
                                    "Optional source EV-disabled stat comparison is not imported with the initial-options system.",
                                    "Source evolution animation/presentation and item artwork remain pending."], records=records)
    return {OUTPUT: "\n".join(lines), MANIFEST: json.dumps(manifest, indent=2) + "\n"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, text in build().items():
        if args.check:
            assert path.is_file() and path.read_text() == text, f"Regenerate {path.relative_to(ROOT)}"
        else:
            path.write_text(text)
    print("PASS: pinned source evolution rows, 391 identities and explicit landmark bindings")


if __name__ == "__main__":
    main()
