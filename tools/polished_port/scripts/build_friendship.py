#!/usr/bin/env python3
"""Import authenticated source happiness events and growth boundary fixtures."""
import argparse
import hashlib
import json
import re

import build_battle_suite as source
import build_trainer_attributes as trainers

ROOT = source.ROOT
MANIFEST = ROOT/'tools/polished_port/manifests/friendship.json'
HEADER = ROOT/'include/constants/polished_happiness.h'
DATA = ROOT/'src/data/polished_happiness.h'
VECTORS = ROOT/'test/battle/polished_growth_vectors.h'
HAPPINESS_VECTORS = ROOT/'test/battle/polished_friendship_vectors.h'


def reference_change(value, delta, bell, luxury):
    # Interpret the byte add/carry branches, then the two guarded increments.
    result = (value + delta) & 255
    if delta < 0:
        return result if value >= -delta else 0
    if value + delta > 255:
        return 255
    for extra in (bell, luxury):
        if extra and result != 255:
            result += 1
    return result


def build():
    files = source.authenticated_sources()
    paths = ('constants/pokemon_data_constants.asm', 'data/events/happiness_changes.asm',
             'engine/events/happiness_egg.asm', 'engine/pokemon/level_up_happiness.asm',
             'engine/pokemon/experience.asm', 'data/growth_rates.asm',
             'engine/battle/core.asm', 'data/trainers/leaders.asm', 'engine/items/item_effects.asm')
    text = {p: files[p]['text'] for p in paths}
    constants = text[paths[0]]
    events = re.findall(r'^\s*const (HAPPINESS_\w+)', constants.split('; ChangeHappiness arguments',1)[1].split('DEF NUM_HAPPINESS_CHANGES',1)[0], re.M)
    changes = [[int(v.strip()) for v in row.split(',')] for row in re.findall(r'^\s*db ([^;\n]+)',text[paths[1]],re.M)]
    assert len(events) == len(changes) == 23 and all(len(row)==3 for row in changes)
    thresholds = [int(re.search(rf'DEF HAPPINESS_THRESHOLD_{i} EQU (\d+)',constants)[1]) for i in (1,2)]
    assert thresholds == [100,160]
    change = text[paths[2]].split('ChangeHappiness:',1)[1].split('StepHappiness::',1)[0]
    assert 'bit MON_IS_EGG_F, [hl]\n\tret nz' in change
    assert 'cp $64' in change and 'call GetExtraHappiness' in change
    assert 'Soothe Bell adds 1' in change and 'Luxury Ball adds 1' in change
    home = text[paths[3]]
    assert 'and $7f' in home and 'HAPPINESS_GAINLEVELATHOME' in home and 'GetWorldMapLocation' in home
    core = text[paths[6]]
    assert 'call HasEnemyFainted\n\tcall nz, PlayerMonFaintHappinessMod' in core
    assert 'add 30' in core.split('PlayerMonFaintHappinessMod:',1)[1].split('AskUseNextPokemon:',1)[0]
    boss = core.split('InitEnemy:',1)[1].split('ExitBattle:',1)[0]
    assert 'call IsBossTrainer' in boss and 'jr z, .skipfaintedmon' in boss
    assert core.count('farcall LevelUpHappinessMod') == 1
    items = text[paths[8]].split('GuardSpec:',1)[1].split('BlueCard:',1)[0]
    assert items.count('jmp nz, WontHaveAnyEffect_NotUsedMessage') == 3
    assert 'farcall _ForceRaiseStat' in items and 'ld a, [wFailedMessage]' in items
    assert 'ld c, HAPPINESS_USEDXITEM' in items
    assert 'Pokémon have 0 experience at level 1' in text[paths[4]]
    formulas = [tuple(map(int,row)) for row in re.findall(r'^\s*growth_rate (\d+), (\d+),\s*(-?\d+),\s*(\d+),\s*(\d+)',text[paths[5]],re.M)]
    assert formulas == [(1,1,0,0,0),(6,5,-15,100,140),(4,5,0,0,0),(5,4,0,0,0)]
    vectors = [[0 if level==1 else a*level**3//b+c*level**2+d*level-e for level in range(1,101)] for a,b,c,d,e in formulas]
    bosses = re.findall(r'^\s*db (\w+)\s*$',text[paths[7]],re.M)
    bindings = {f'TRAINER_POLISHED_{target}': cls in bosses for target,(cls,_) in trainers.BINDINGS.items()}
    assert len(bindings)==21 and sum(bindings.values())==1
    header = ['/* Generated from pinned Polished Crystal happiness constants. */',
              '#ifndef GUARD_CONSTANTS_POLISHED_HAPPINESS_H', '#define GUARD_CONSTANTS_POLISHED_HAPPINESS_H']
    header += [f'#define POLISHED_{event} {i}' for i,event in enumerate(events)]
    header += [f'#define POLISHED_HAPPINESS_COUNT {len(events)}', '#define POLISHED_HAPPINESS_LOW 100', '#define POLISHED_HAPPINESS_HIGH 160', '#endif', '']
    data = ['/* Generated by build_friendship.py from authenticated source data. */',
            'static const s8 sPolishedHappinessChanges[POLISHED_HAPPINESS_COUNT][3] = {']
    data += [f'    [POLISHED_{event}] = {{{", ".join(map(str,row))}}},' for event,row in zip(events,changes)]
    data += ['};','#if !IS_FRLG','static const u16 sPolishedBossTrainers[] = {']
    data += [f'    {trainer},' for trainer,boss in bindings.items() if boss]
    data += ['};','#endif','']
    fixture = ['/* Generated from the four authenticated source growth formulas. */','static const u32 sPolishedGrowthVectors[4][100] = {']
    fixture += ['    {'+', '.join(map(str,row))+'},' for row in vectors]
    fixture += ['};','']
    reference = [reference_change(value,row[(value>=100)+(value>=160)],bell,luxury)
                 for row in changes for value in range(256) for bell in (0,1) for luxury in (0,1)]
    arithmetic = ['/* Independent byte/carry reference, event/value/bell/luxury order. */',
                  'static const u8 sPolishedFriendshipVectors[] = {']
    arithmetic += ['    '+', '.join(map(str,reference[i:i+32]))+',' for i in range(0,len(reference),32)]
    arithmetic += ['};','']
    report = dict(source_commit=source.source.PIN,source_variant='default; FAITHFUL undefined',
        source_anchors={p:files[p]['sha'] for p in paths},events=dict(zip(events,changes)),
        thresholds=thresholds,reference_cases=len(reference),reference_sha256=hashlib.sha256(bytes(reference)).hexdigest(),
        growth_vectors=400,boss_classes=bosses,registered_boss_bindings=bindings,
        complete_behavior_parity=False,
        remaining=['Walking cadence, vitamins/EV berries/Rare Candy item dispatch, grooming and other field event bindings remain open.',
                   'Full residual/faint/replacement sequencing, unregistered trainers, facility/link rules and battle-end persistence remain open.',
                   'Battle item stat boost magnitude and other item mechanics remain open; this suite binds successful-use happiness only.',
                   'Source location identity uses existing mapped region sections; full geographic provenance and exact presentation/RNG remain open.'])
    return {HEADER:'\n'.join(header), DATA:'\n'.join(data), VECTORS:'\n'.join(fixture), HAPPINESS_VECTORS:'\n'.join(arithmetic), MANIFEST:json.dumps(report,indent=2)+'\n'}


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check',action='store_true')
    args=p.parse_args()
    for path,content in build().items():
        if args.check: assert path.read_text()==content, f'Regenerate {path}'
        else: path.write_text(content)
    print('PASS: 23 source happiness events, 23552 byte cases, 400 growth vectors and 21 boss bindings')
