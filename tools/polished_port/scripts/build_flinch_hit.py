#!/usr/bin/env python3
"""Pin source move-effect flinch eligibility against sleeping/frozen targets."""
import argparse
import json

import build_pokemon_learnsets as source


def build():
    files = source.sources()
    rows = [[value.strip() for value in line[5:].split(',')] for line in
            source.default_lines(files['data/moves/moves.asm']) if line.startswith('move ')]
    selected = []
    for identity, row in zip(source.move_identities(files)[1:], rows, strict=True):
        assert identity['source_move'] == row[0]
        if row[1] in ('EFFECT_FLINCH_HIT', 'EFFECT_STOMP'):
            selected.append(dict(**identity, source_effect=row[1]))
    assert [row['source_move'] for row in selected] == [
        'AIR_SLASH', 'STOMP', 'HEADBUTT', 'BITE', 'WATERFALL', 'ICICLE_CRASH',
        'IRON_HEAD', 'EXTRASENSORY', 'ROCK_SLIDE', 'HYPER_FANG', 'ZEN_HEADBUTT',
        'ASTONISH', 'DARK_PULSE']
    effects = [line.split()[1] for line in source.default_lines(files['constants/move_effect_constants.asm'])
               if line.startswith('const EFFECT_')]
    pointers = [line.split()[1] for line in source.default_lines(files['data/moves/effects_pointers.asm'])
                if line.startswith('dw ')]
    mapping = dict(zip(effects, pointers, strict=True))
    scripts = files['data/moves/effects.asm']
    common = ['checkobedience', 'usedmovetext', 'doturn', 'hastarget', 'checkhit',
              'checkpriority', 'critical', 'damagestats', 'damagecalc', 'stab',
              'damagevariation', 'moveanim', 'failuretext', 'applydamage',
              'criticaltext', 'supereffectivetext', 'postfainteffects', 'effectchance',
              'flinchtarget', 'posthiteffects', 'endmove']
    for effect, label, end in [('EFFECT_FLINCH_HIT', 'FlinchHit', 'PoisonHit'),
                               ('EFFECT_STOMP', 'Stomp', 'SolarBeam')]:
        assert mapping[effect] == label
        block = scripts.split('\n'+label+':\n', 1)[1].split('\n'+end+':', 1)[0]
        expected = common.copy()
        if label == 'Stomp':
            expected.insert(expected.index('moveanim'), 'doubleminimizedamage')
        assert [line for line in source.default_lines(block) if line] == expected
    commands = files['engine/battle/effect_commands.asm']
    gate = commands.split('\nBattleCommand_flinchtarget:\n', 1)[1].split('\nFlinchTarget:', 1)[0]
    assert [line for line in source.default_lines(gate) if line] == [
        'call CheckSubstituteOpp', 'ret nz', 'ld a, BATTLE_VARS_STATUS_OPP',
        'call GetBattleVar', 'and 1 << FRZ | SLP_MASK', 'ret nz',
        'call CheckOpponentWentFirst', 'ret nz', 'ld a, [wEffectFailed]',
        'and a', 'ret nz']
    # Item/Stench post-hit flinches call FlinchTarget directly, bypassing this gate.
    posthit = commands.split('\n.rocky_helmet_done\n', 1)[1].split('\nCheckStatHerbsAfterIntimidate:', 1)[0]
    assert 'cp STENCH\n\tld c, 10\n\tjr z, .do_flinch_up' in posthit
    assert 'cp HELD_FLINCH_UP\n.do_flinch_up\n\tcall z, .flinch_up' in posthit
    assert 'ld b, flinchtarget_command\n\tcall HasBattleCommand\n\tret z' in posthit
    assert 'call c, FlinchTarget\n\tret' in posthit
    report = dict(source_repository='Rangi42/polishedcrystal', source_commit=source.PIN,
        source_variant='default (FAITHFUL undefined)', profile='B_POLISHED_MOVE_BALANCE',
        scope='The thirteen source FlinchHit/Stomp moves in singles without either active gimmick.',
        moves=selected,
        rules=['After damage and effectchance, flinchtarget rejects Substitute, sleep and freeze before setting a flinch.',
               'The target status is checked when the effect executes, before that target wakes or thaws during its action.',
               'Sleep Talk, natural thaw and source self-thaw can therefore proceed without a move-effect flinch; a rejected flinch does not activate Steadfast.',
               'King\'s Rock, other HELD_FLINCH_UP items and Stench use a separate direct FlinchTarget path and do not inherit the sleep/freeze rejection.'],
        adapter='Reject only the mapped move-effect flinch at its existing execution gate when the target is asleep or frozen. Preserve native hit, Substitute, ability, acted-turn and format gates; do not change status timers or action canceler ordering.',
        gaps=['This ports sleep/freeze eligibility for these thirteen moves, not all flinch eligibility, source chance rolls, recharge clearing, ability suppression, AI or original presentation.',
              'Natural freeze versus effective item/Stench flinch, sleep versus effective flinch and full action-cancellation ordering remain separate audits.',
              'Optional flinching moves, other statuses, doubles and either active gimmick retain their existing paths. Item/Stench behavior beyond this gate distinction is not certified.'])
    header = f'/* Generated by build_flinch_hit.py from Polished Crystal {source.PIN}. */\n'
    header += 'static const u8 sPolishedFlinchHitMoves[MOVES_COUNT] = {\n'
    header += ''.join(f"    [{row['target_move']}] = TRUE,\n" for row in selected)
    header += '};\n'
    return {source.ROOT/'src/data/polished_flinch_hit.h': header,
            source.ROOT/'tools/polished_port/manifests/flinch_hit.json': json.dumps(report, indent=2)+'\n'}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, expected in build().items():
        if args.check:
            assert path.read_text() == expected, f'Regenerate {path}'
        else:
            path.write_text(expected)
    print('PASS: thirteen pinned flinch-hit moves reject sleeping and frozen targets')
