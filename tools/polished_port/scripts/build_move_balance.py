#!/usr/bin/env python3
"""Import the twelve unambiguous move-balance rows from the pinned default build.

Variable/fixed damage, typeless sentinels and accuracy-bypass differences remain
separate behavior audits. This importer does not infer effect or RNG parity.
"""
import argparse
import json
import build_pokemon_learnsets as source

ROOT = source.ROOT
SELECTED = ('CUT', 'FLY', 'TAKE_DOWN', 'SING', 'SUPERSONIC', 'STRENGTH',
            'FIRE_SPIN', 'DIG', 'SCALD', 'CRABHAMMER', 'OCTAZOOKA', 'WHIRLPOOL')


def build():
    files = source.sources()
    rows = [[v.strip() for v in line[5:].split(',')] for line in
            source.default_lines(files['data/moves/moves.asm'].split('Moves::',1)[1])
            if line.startswith('move ')]
    identities = source.move_identities(files)[1:]
    assert len(rows) == len(identities) == 255
    records = []
    for identity, row in zip(identities, rows, strict=True):
        move, effect, power, type_, accuracy, pp, chance, category = row
        assert identity['source_move'] == move
        if move not in SELECTED:
            continue
        power, accuracy = int(power), int(accuracy)
        assert power != 1 and 0 <= power <= 255 and 1 <= accuracy <= 100 and type_ != 'UNKNOWN_T'
        records.append(dict(**identity, power=power, accuracy=accuracy, type=type_,
                            category=category, source_effect=effect, source_chance=int(chance)))
    assert {r['source_move'] for r in records} == set(SELECTED)
    generated = f'/* Generated by build_move_balance.py from Polished Crystal {source.PIN}. */\n'
    table = generated + '#ifndef GUARD_POLISHED_MOVE_BALANCE_DATA_H\n#define GUARD_POLISHED_MOVE_BALANCE_DATA_H\n\n'
    table += '// Select at compile time: ordinary move getters keep their native cost.\n'
    table += '#if B_POLISHED_MOVE_BALANCE\n#define POLISHED_BALANCE(source, native) (source)\n#else\n#define POLISHED_BALANCE(source, native) (native)\n#endif\n\n'
    for r in records:
        for field, value in (('POWER', r['power']), ('ACCURACY', r['accuracy']),
                             ('TYPE', 'TYPE_' + r['type']),
                             ('CATEGORY', 'DAMAGE_CATEGORY_' + r['category'])):
            table += f"#define POLISHED_{r['source_move']}_{field} {value}\n"
    table += '\n#endif\n'
    report = dict(source_repository='Rangi42/polishedcrystal', source_commit=source.PIN,
        source_variant='default (FAITHFUL undefined)',
        source_files=['data/moves/moves.asm', 'constants/move_constants.asm'],
        moves=records,
        scope='Power, accuracy, type and physical/special/status category for twelve reviewed ordinary rows. Stable target move IDs.',
        gaps=['Other source move rows remain under their separately documented adapters or native definitions.',
              'Fixed/variable damage and typeless/accuracy-bypass differences need behavioral review.',
              'Effect implementations, secondary chances, flags, priority, damage rounding, accuracy RNG and animation remain separate source-parity work.'])
    return {ROOT/'src/data/polished_move_balance.h':table,
            ROOT/'tools/polished_port/manifests/move_balance.json':json.dumps(report,indent=2)+'\n'}


if __name__ == '__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    for path,text in build().items():
        if a.check: assert path.read_text()==text, f'Regenerate {path}'
        else: path.write_text(text)
    print('PASS: twelve pinned default move-balance rows; special-case effects remain explicitly scoped out')
